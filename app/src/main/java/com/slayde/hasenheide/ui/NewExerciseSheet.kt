package com.slayde.hasenheide.ui

import androidx.compose.runtime.Composable
import com.slayde.hasenheide.data.종목

/**
 * 새 종목 / 종목 편집 시트 (시안 v18~v20 `새종목시트`) — 종목 화면 · 종목 넣기 시트(루틴 · 운동 중)가 **같이** 쓴다.
 *
 * ── 2단계 소유: EX(종목) 도우미가 속을 채운다. 매개변수(이름 · 꼴)는 바꾸지 않는다 ──
 * RT · W 도우미는 **부르기만** 한다. 새 매개변수가 꼭 필요하면 기본값을 단다.
 *
 * 시안 동작: 위끝 20% 고정 · 이름 칸 + 초성 검색(`종목사전.찾기`) · 칸(필수) · 운동 목표 부위 그림 · 주동/협응 ·
 * 기본 세팅 세트 줄 · 같은 이름이면 번호 딱지 · [저장]. 저장은 `앱데이터.종목더하기` (편집이면 그 종목을 바꾼다).
 *
 * @param 편집 null = 새 종목, 아니면 그 종목을 고친다
 * @param 처음이름 이름 칸에 미리 넣을 글 (넣기 시트에서 찾던 글)
 * @param 저장 저장된 종목(새 id 포함)을 돌려준다 — 부른 쪽이 바로 넣을 때 쓴다
 */
@Composable
fun 새종목시트(
    상태: 앱상태,
    닫기: () -> Unit,
    저장: (종목) -> Unit = {},
    편집: 종목? = null,
    처음이름: String = "",
) {
    // 1단계 틀 — EX 도우미가 시안대로 채운다. 지금은 닫기만 있다
    시트(if (편집 != null) "${편집.이름} 편집" else "새 종목", 닫기, 위끝고정 = true) {
        글("준비 중")
    }
}
