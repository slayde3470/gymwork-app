/** 운동 중인 종목 한 줄. 기록 칸은 비어 있을 수 있다(체크를 풀면 그 칸만 빈다) */
data class 세션종목(
    val 이름: String,
    val 세트: Int,
    /** 루틴에 원래 정해둔 세트 수 — 달성도의 분모. 운동 중 추가해도 안 바뀐다 */
    val 계획세트: Int,
    val 무게: Double,
    val 횟수: Int,
    val 휴식: Int,
    val 기록: List<세트?> = emptyList(),
    /** 아직 안 한 세트의 값을 따로 고쳐둔 것 */
    val 예정값: List<세트?> = emptyList(),
    /** 세트마다의 휴식(초) */
    val 휴식들: List<Int?> = emptyList(),
    val 임시: Boolean = false,
    /** '여기까지'로 마친 종목 */
    val 마감: Boolean = false,
    val 슈퍼: String? = null,
    /** 플랜에서 온 줄이면 그 플랜 id (10-01) */
    val 플랜id: String? = null,
    /** 종목 id (10-05 · 스키마 15). null = 옛 줄 → 이름으로 찾는다 */
    val 종id: String? = null,
)

/** 방금 끝낸 세트 줄 위에서 도는 휴식 */
data class 휴식중(
    val k: Int,
    val 끝시각: Long,
    /** 휴식이 끝나고 '다음으로 갈까요?'를 묻는 중 */
    val 물음: Boolean = false,
    /** 슈퍼세트 한 바퀴 뒤 돌아갈 자리 */
    val 다음i: Int? = null,
    val 다음s: Int? = null,
    /** 처음 정한 휴식 길이(초) — 남은 비율로 색을 바꾼다 */
    val 총초: Int = 0,
    /** 어느 종목의 세트 줄에서 도는지. -1 = 옛 기록(지금 종목) */
    val 종목: Int = -1,
)

data class 운동세션(
    val 루틴id: String,
    val 루틴이름: String,
    val 시작시각: Long,
    /** 지금 종목 번호 */
    val i: Int = 0,
    /** 지금 할 세트 번호 */
    val s: Int = 0,
    /** 지금 할 세트의 무게 · 횟수 (체크하면 이 값으로 기록된다) */
    val 무게: Double = 0.0,
    val 횟수: Int = 0,
    val 종목들: List<세션종목> = emptyList(),
    val 휴식: 휴식중? = null,
    /** 마무리 화면을 보는 중 */
    val 끝화면: Boolean = false,
    /** 마무리 화면에 들어온 시각 — 여기서 운동 시간이 멈춘다 */
    val 끝시각: Long? = null,
    /** 마지막으로 손댄 시각 — 오래 손대지 않으면 저절로 끝낸다 (09-25 메모). 0 = 모름(옛 파일) → 시작시각 */
    val 마지막: Long = 0L,
    /** 그 날만 조절해서 시작했다 — 저장할 때 루틴에 되돌려 적지 않는다 (09-27) */
    val 조절됨: Boolean = false,
    /**
     * 마무리 화면에 머물렀던 시간의 합(ms) — 운동 시간에서 뺀다 (10-05 검수).
     * 전에는 [운동으로 돌아가기] 가 시작시각을 미뤘는데, 시작시각은 '이 운동' 을 가르는 값이라 되돌리기 · 보던 칸이 끊겼다
     */
    val 멈춘: Long = 0L,
)

/** 앱 전체 자료 — 이것 하나를 통째로 파일에 저장한다 */
data class 앱데이터(
    val 종목표: List<종목> = emptyList(),
    val 카테고리: List<String> = 기본카테고리,
    val 루틴들: List<루틴> = emptyList(),
    /** "2026-09-21" → 그 날 기록 */
    val 기록: Map<String, 날기록> = emptyMap(),
    /** "2026-09-22" → 루틴 id (앞으로 할 날에 미리 깔아둔 것) */
    val 예정: Map<String, String> = emptyMap(),
    val 일정: Map<String, List<String>> = emptyMap(),
    val 설정: 설정값 = 설정값(),
