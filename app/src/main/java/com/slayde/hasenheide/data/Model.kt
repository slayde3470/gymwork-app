package com.slayde.hasenheide.data

/**
 * 앱이 다루는 모든 자료의 모양.
 *
 * ── 왜 전부 data class(바꿀 수 없는 값)인가 ──
 * 화면(Compose)은 "값이 바뀌었나?"를 보고 다시 그린다.
 * 값을 제자리에서 고치면 화면이 바뀐 줄 모를 수 있다.
 * 그래서 고칠 때는 언제나 새 값을 만들어 통째로 바꾼다 (copy).
 *
 * 이 파일에는 안드로이드 기능을 쓰지 않는다 → 컴퓨터에서 따로 검사할 수 있다.
 */

/** 종목 — 벤치프레스 같은 운동 하나 */
data class 종목(
    val 이름: String,
    val 부위: String,
    val 장비: String = "",
    /** 참고 링크 — 주소는 감추고 이 글씨만 보인다 (09-24) */
    val 참고글: String? = null,
    val 참고url: String? = null,
    /** 달력 칸에만 쓰는 짧은 이름. 비어 있으면 종목 이름을 따라간다 */
    val 달력이름: String? = null,
    /** 1RM 목표(kg) — 캘린더 판에서 지금 속도 · 도달 예상을 보인다 (09-27). 볼륨 목표는 두지 않는다 */
    val 목표1RM: Double? = null,
    /**
     * 종목 사진 (10-02 · 08 시안 4절) — 앱 안 filesDir/photos 의 파일 이름. 최대 10장.
     * 백업 파일에는 **이름만** 들어간다 (사진 파일은 들어가지 않는다 → 다른 폰에서 가져오면 사진은 비어 보인다)
     */
    val 사진: List<String> = emptyList(),
    /**
     * 종목 id (10-05 · 스키마 15 · 시안 v19 D ②) — **같은 이름 종목을 허용**하려고. 종목설정 · 줄의 [종id] 가 이것을 가리킨다.
     * 옛 종목(스키마 14 이하)은 읽을 때 이름 그대로가 id 가 된다. 새로 만드는 종목은 [새종목id] 로 ("종" + 시각 36진수).
     * 기본값 = 이름 — 화면이 `종목(이름, 부위)` 로 만들어도 옛 동작 그대로 (같은 이름을 또 만들 땐 [앱데이터.종목더하기] 가 id 를 바꿔 준다)
     */
    val id: String = 이름,
    /**
     * 사용자가 고른 근육 → 역할 (10-05 · 시안 v20 ⑤ 새 종목 시트). 값은 "P" 주동근 · "Y" 협응근 둘뿐.
     * 옛 "S"(보조근) 는 읽을 때 "Y" 로. 비어 있으면 내장 규칙(근육자료.규칙 · 부위기본)을 쓴다.
     * 열쇠는 세부 부위 id (chest_mid · lats · glutes …, [종목사전.세부부위])
     */
    val 근육: Map<String, String> = emptyMap(),
)

/** 시안의 '칸'(종목 카테고리 — 가슴 · 등 · 하체 · 어깨 · 팔 · 맨몸) = 앱의 [종목.부위] 와 같은 것. 이름만 맞춰 둔다 */
val 종목.칸: String get() = 부위

/** 종목 기본 세팅의 세트 한 줄 (10-05 · 시안 v18 C ④ `S.종목설정[열쇠].세트[]` = {w, r, 휴}) */
data class 종목세트(val w: Double, val r: Int, val 휴: Int)

/** 운동 인증샷 한 장 (10-05 · 시안 v17 ⑥) — 앱 안 파일 이름. [고정] = 맨 앞에 고정한 시각(ms), 0 = 고정 안 함 (최대 3장) */
data class 인증사진(val 파일: String, val 때: Long, val 고정: Long = 0L)

/** 운동 보고서에 보일 것 (시안 ua0b `S.설정.보고서보임`) — 루틴 결과는 늘 보인다(v18 홍겸 님) */
data class 보고서보임값(val 프로필: Boolean = true, val 루틴: Boolean = true)

/** 루틴 안에 들어 있는 종목 한 줄 — 세트 · 무게 · 횟수 · 휴식(초) */
data class 루틴종목(
    val 이름: String,
    val 세트: Int = 3,
    val 무게: Double = 20.0,
    val 횟수: Int = 10,
    val 휴식: Int = 90,
    /** 같은 값을 가진 종목끼리 슈퍼세트로 묶인다 */
    val 슈퍼: String? = null,
    /** 세트마다 따로 정한 목표 (기능명세 4-2 · 5-5). 비어 있거나 모자라면 위의 무게 · 횟수를 쓴다 */
    val 세트값: List<세트> = emptyList(),
    /** 세트마다 따로 정한 휴식(초). 비어 있거나 모자라면 위의 휴식을 쓴다 */
    val 휴식값: List<Int> = emptyList(),
    /**
     * 운동 플랜에서 온 줄이면 그 플랜 id (09-30).
     * 이 줄의 무게·횟수는 **플랜이 정한다** → 루틴에서 손으로 고치지 않는다.
     */
    val 플랜id: String? = null,
    /** 종목 id (10-05 · 스키마 15). null = 옛 줄 → 이름으로 찾는다 ([앱데이터.종목찾기]) */
    val 종id: String? = null,
)

/** 루틴 — 가슴날처럼 하루에 하는 운동 묶음. 휴식일도 루틴 한 칸이다 */
data class 루틴(
    val id: String,
    val 이름: String,
    val 휴식일: Boolean = false,
    val 종목: List<루틴종목> = emptyList(),
    /** 캘린더에 순서대로 저절로 깔까 (09-25 메모). 새 루틴은 꺼져 있다. 옛 루틴은 켜진 채로 옮긴다 */
    val 자동생성: Boolean = false,
)

/**
 * 한 세트 — 무게(w) × 횟수(r).
 *
 * [종류] 는 09-29 에 더했다 (20 문서 B-5, 홍겸 님 확정):
 *  · 0 본운동 — 볼륨·1RM 기록에 모두 들어간다
 *  · 1 워밍업 — **사용자가 보는 기록에 띄우지 않고** 볼륨·1RM 어디에도 안 들어간다. 운동 중 체크용
 *  · 2 측정   — 볼륨에서는 빼지만 **1RM 기록에는 들어간다** (그 종목의 가장 좋은 1RM 근거니까)
 */
data class 세트(val w: Double, val r: Int, val 종류: Int = 0)

/** 그 날 한 종목의 기록 */
data class 종목기록(
    val 이름: String,
    val 세트들: List<세트>,
    /** 오늘만 끼운 종목(운동 추가) — 루틴 차원 계산에서 뺀다 */
    val 임시: Boolean = false,
    /** 슈퍼세트로 했으면 묶음 이름 "덤벨컬+해머컬". 같은 묶음끼리만 견준다 */
    val 묶음: String? = null,
    /** 플랜에서 온 줄이면 그 플랜 id (10-01) — 플랜 반영은 이름이 아니라 이것으로 짝짓는다 */
    val 플랜id: String? = null,
    /** 종목 id (10-05 · 스키마 15). null = 옛 기록 → 이름으로 찾는다 */
    val 종id: String? = null,
)

/** 하루 기록 */
data class 날기록(
    val 루틴id: String,
    val 루틴이름: String,
    val 달성: Boolean,
    val 종목들: List<종목기록>,
    val 걸린초: Int = 0,
    /** 시작 · 끝 시각 (09-27: 캘린더 판 "오후 18:05 ~ 19:03"). 0 = 모름(옛 기록) → 보이지 않는다 */
    val 시작시각: Long = 0L,
    val 끝시각: Long = 0L,
)

/** 그 날만 조절 (09-27 캘린더 판 '설정') — 루틴은 그대로, 그 날 운동에만 */
data class 오늘조절(
    /** 전체 볼륨 % — 세트마다 무게에 곱한다 */
    val 볼륨: Int = 100,
    /** 세트마다 무게에 더한다(kg) */
    val 무게: Double = 0.0,
    /** 종목마다 세트 수에 더한다 */
    val 세트: Int = 0,
) {
    val 그대로: Boolean get() = 볼륨 == 100 && 무게 == 0.0 && 세트 == 0
}

/** 설정 */
data class 설정값(
    val 자동진행: Boolean = true,
    val 넘어가기전확인: Boolean = false,
    val 소리진동: Boolean = true,
    val 화면유지: Boolean = true,
    /** 무게 ＋ − 한 번의 폭 */
    val 무게폭: Double = 1.0,
    /** 새 종목을 넣을 때의 휴식(초) */
    val 기본휴식: Int = 60,   // 09-24: 기본 휴식 1분
    /** 새 종목을 넣을 때의 세트 수 (09-21 메모: 보통 5세트) */
    val 기본세트: Int = 1,   // 09-22: 새 종목은 1세트로 시작, ＋ 로 늘린다
    // ── 볼륨 자동 올리기 (09-24, 업데이트 예정 ⑲) ──
    /** 루틴을 성공하면 다음 루틴 목표를 저절로 올린다 */
    val 볼륨켬: Boolean = false,
    /** "%" 또는 "kg" */
    val 볼륨방식: String = "%",
    val 볼륨값: Double = 2.5,
    /** "성공" = 계획한 세트를 다 끝낸 날만 · "항상" */
    val 볼륨언제: String = "성공",
    /** 어디에 붙일까 — "횟수"(상한을 넘으면 무게로) · "무게" */
    val 볼륨배분: String = "횟수",
    /** 횟수에 붙일 때의 상한 */
    val 횟수상한: Int = 12,
    /** 향상도 기준: 0 = 직전 같은 루틴, 1 · 3 · 6 · 12 = 몇 개월 전 */
    val 기준: Int = 3,
    /** 휴식 끝 진동 세기 1 약 · 2 중 · 3 강 (09-25 메모) */
    val 진동세기: Int = 2,
    /** 휴식 끝 진동 길이(ms) (09-25 메모) */
    val 진동시간: Int = 1000,
    /** 화면 번호 보기 — 시험 기간 동안 칸마다 작은 번호 (09-26) */
    val 번호보기: Boolean = true,
    // ── 운동 중 그림 (10-02 · 08 3절 · 07 근육지도) ──
    /** 위쪽 그림 칸 — "근육 2장" · "근육 + 사진" · "사진 1장" · "사진 2장" · "숨김" (근육표.배너목록) */
    val 배너: String = "근육 2장",
    /** 가장 빨갛던(20단계) 근육이 원래 색으로 돌아오는 시간(시간). 6 ~ 168 */
    val 회복시간: Int = 24,
    /** 근육 색표 — "heat" 노랑→빨강 · "red" · "blue" */
    val 색표: String = "heat",
    // ── 프로필 · 보고서 (10-05 · 스키마 15 · 시안 v10~v18) ──
    /** 닉네임 — 12자까지 (시안 `S.설정.닉네임`) */
    val 닉네임: String = "",
    /** 프로필 사진 — 앱 안 파일 이름 (시안은 브라우저 저장). null = 없음 → 닉네임 첫 글자 · 사람 그림 */
    val 프로필사진: String? = null,
    /** SNS 링크 — 몇 개든. http(s) 주소만 ([링크주소] 로 다듬어 넣는다 · 시안 `S.설정.링크`) */
    val 링크: List<String> = emptyList(),
    /** 운동 보고서에 보일 것 (시안 `S.설정.보고서보임`) */
    val 보고서보임: 보고서보임값 = 보고서보임값(),
    /** 보고서 큰 운동 칸에 더할 것 — [큰운동표] 4번째부터의 키, 최대 2개, 표 순서 (시안 `S.설정.큰운동추가`) */
    val 큰운동추가: List<String> = emptyList(),
    /** 프로필 업적 줄 정렬 — "최신순"(기본) · "오래된순" · "가나다순" · "직접"(끌어 옮겼을 때) (시안 `S.설정.업적정렬`) */
    val 업적정렬: String = "최신순",
)

/** 체중 한 줄 (10-02 · 스키마 14) — 바꾼 시각 · kg */
data class 체중값(val 시각: Long, val kg: Double)

/** 써보면서 적는 수정 메모 — 어느 화면에서 적었는지 함께 남긴다 */
data class 수정메모(
    val 시각: Long,
    val 화면: String,
    val 글: String,
    /** 메모를 적기 바로 전에 한 동작들 (09-24 메모) — 무엇을 하다 적었는지 알 수 있게 */
    val 흔적: List<String> = emptyList(),
)

