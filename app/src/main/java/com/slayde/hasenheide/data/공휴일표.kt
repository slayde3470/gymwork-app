private val 공휴일날들: Set<String> = 공휴일표.flatMap { (해, 월일들) -> 월일들.map { "$해-$it" } }.toSet()

/** 표가 다루는 해 (이 밖의 해는 공휴일이 없는 것으로 친다) */
val 공휴일표해: IntRange = 공휴일표.keys.min()..공휴일표.keys.max()

/** 공휴일(대체공휴일 · 선거일 포함)인 날짜 "yyyy-MM-dd" 인가 */
fun 공휴일인가(날: String): Boolean = 날 in 공휴일날들
