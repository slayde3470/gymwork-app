package com.slayde.hasenheide.data

import kotlin.math.max
import kotlin.math.roundToInt

/**
 * 기록 방식 (10-12 홍겸 님 · 문서/기록방식_설계.md 1단계) — 종목마다 무게 칸이 무엇을 뜻하는지.
 *
 *  · 무게 (기본) — 무게 칸 = 든 무게
 *  · 맨몸 — 무게 칸 = **추가 무게**(기본 0). 실제 무게 = 체중 + 추가 (09-27 결정)
 *  · 어시스트 — 무게 칸 = **보조 무게**. 실제 무게 = 체중 − 보조 (0 아래면 0)
 *  · 횟수만 — 맨몸 복근. 무게 칸을 숨기고 기록 무게는 0 (볼륨 0) · 피로는 체중 × 0.6 (2단계)
 *  · 시간 — 버티기. 무게 칸 없음 · 횟수 칸이 시간(m:ss) · [세트.r] 에 **초**가 들어간다. 볼륨 0 · 피로는 초 ÷ [회당초] 회로 환산 (2단계). 타이머는 3단계
 *  · 커스텀 종목은 [종목.방식] 에 고른 방식을 가진다 — 있으면 이름 자동보다 먼저 ([방식])
 *
 * ── 어디서 바꾸나 ──
 * 입력 칸(루틴 · 기본 세팅 · 운동 중)은 늘 **입력값**(추가 · 보조) 그대로 둔다.
 * **기록(날기록)에 남길 때만** 실제 무게로 바꿔 넣는다 → 볼륨 · 1RM · 업적 · 통계가 고칠 것 없이 맞게 나온다.
 * 세션 값으로 바로 세는 곳(운동 중 볼륨 · 근육 피로 · 끝내기 전 보고서)은 같은 함수([실제세트들])로 바꿔서 센다.
 *
 * ── 건드리지 않는 것 ──
 *  · 플랜 줄(플랜id) — 플랜이 따로 셈한다 (처방 무게가 이미 유효 부하)
 *  · 옛 기록 — 맨몸 무게 0 으로 적힌 것은 그대로 둔다 (지금처럼 체중 × 0.6 으로 셈)
 *  · 체중을 모르면(0) 바꾸지 않는다
 *
 * 이 파일은 안드로이드를 쓰지 않는다 → 시험(RecordModeTest.kt)이 컴퓨터에서 돈다.
 */
enum class 기록방식 { 무게, 맨몸, 어시스트, 횟수만, 시간 }

/** 이름으로 자동 정하는 표 — 종목 전수조사 (문서/조사/종목전수조사_2026-10-12.md) */
object 기록방식표 {
    /** 시간 (버티기) — 마운틴 클라이머는 10-12 홍겸 님이 시간으로 확정 */
    val 시간들: Set<String> = setOf("플랭크", "사이드 플랭크", "할로우 바디 홀드", "마운틴 클라이머")

    /** 횟수만 — 맨몸으로만 하는 복근 (10-12 홍겸 님: 중량이 아니면 횟수만). 중량 복근(케이블 크런치 등)은 이름이 달라 무게 */
    val 횟수만들: Set<String> = setOf(
        "크런치", "리버스 크런치", "싯업", "행잉 레그 레이즈", "라잉 레그 레이즈", "바이시클 크런치",
        "러시안 트위스트", "앱 롤아웃", "데드 버그", "슈퍼맨",
    )

    /** 이름에 '어시스트' · '어시스티드' 가 들면 어시스트 */
    fun 어시스트이름(이름: String): Boolean = 이름.contains("어시스트") || 이름.contains("어시스티드")
}

/**
 * 이름 (+ 장비) 으로 방식을 찾는다 — 사전의 다른 이름도 대표 이름으로 본다 ("할로우 홀드" = "할로우 바디 홀드").
 * 차례: 시간 → 횟수만 → 어시스트 → 맨몸(장비) → 무게. [장비] 가 비어 있으면 사전의 장비를 쓴다
 */
fun 이름으로방식(이름: String, 장비: String = ""): 기록방식 {
    val 사 = 종목사전.정확히(이름)
    val 대표 = 사?.이름 ?: 이름
    return when {
        대표 in 기록방식표.시간들 -> 기록방식.시간
        대표 in 기록방식표.횟수만들 -> 기록방식.횟수만
        기록방식표.어시스트이름(이름) || 기록방식표.어시스트이름(대표) -> 기록방식.어시스트
        장비.ifBlank { 사?.let { 종목사전.장비(it) } ?: "" } == "맨몸" -> 기록방식.맨몸
        else -> 기록방식.무게
    }
}

/** 줄(종id · 이름)이 가리키는 종목의 방식 — 종목표에 있으면 그 종목의 장비를 쓴다 */
fun 앱데이터.방식(종id: String?, 이름: String): 기록방식 {
    val t = 종목찾기(종id, 이름)
    // 커스텀 종목이 새 종목 시트에서 고른 방식이 있으면 그것이 먼저 (2단계 · 10-12) — 없으면 이름으로 자동
    t?.방식?.let { n -> 기록방식.values().firstOrNull { it.name == n }?.let { return it } }
    return 이름으로방식(t?.이름 ?: 이름, t?.장비.orEmpty())
}

/** 무게 칸이 있는 방식인가 — 횟수만 · 시간은 무게 칸을 숨기고 값도 쓰지 않는다 (2단계) */
fun 기록방식.무게칸있음(): Boolean = this != 기록방식.횟수만 && this != 기록방식.시간

/** 시간 방식인가 — 횟수 칸이 '시간(m:ss)' 이고 [세트.r] 에 초가 들어 있다 */
fun 기록방식.시간칸(): Boolean = this == 기록방식.시간

/** 입력 칸 값 → 기록에 남길 실제 무게. 맨몸 = 체중 + 추가 · 어시스트 = 체중 − 보조(0 아래면 0). 체중을 모르면 그대로 */
fun 실제무게(방식: 기록방식, 입력: Double, 체중: Double): Double = when {
    체중 <= 0.0 -> 입력
    방식 == 기록방식.맨몸 -> 무게반올림(체중 + 입력)
    방식 == 기록방식.어시스트 -> 무게반올림(max(0.0, 체중 - 입력))
    else -> 입력
}

/** 기록의 실제 무게 → 입력 칸 값 ([실제무게] 의 거꾸로) — 지난 기록을 세션으로 불러올 때 */
fun 입력무게(방식: 기록방식, 실제: Double, 체중: Double): Double = when {
    체중 <= 0.0 -> 실제
    방식 == 기록방식.맨몸 -> 무게반올림(max(0.0, 실제 - 체중))
    방식 == 기록방식.어시스트 -> 무게반올림(max(0.0, 체중 - 실제))
    else -> 실제
}

/**
 * 세션(입력값)의 세트들 → 기록에 남길 실제 무게 세트들. 플랜 줄(플랜id)은 그대로.
 * 저장 · 운동 중 볼륨 · 근육 피로 · 끝내기 전 보고서가 모두 이 함수 하나를 쓴다
 */
fun 앱데이터.실제세트들(종id: String?, 이름: String, 플랜id: String?, 세트들: List<세트>): List<세트> {
    if (플랜id != null || 세트들.isEmpty()) return 세트들
    val 방 = 방식(종id, 이름)
    // 횟수만 · 시간은 무게가 없다 — 칸을 숨겨도 남아 있을 수 있는 옛 값(종목 방식을 나중에 바꾼 경우)이 볼륨에 새지 않게 0 으로 (2단계)
    if (!방.무게칸있음()) return 세트들.map { if (it.w == 0.0) it else it.copy(w = 0.0) }
    if (방 != 기록방식.맨몸 && 방 != 기록방식.어시스트) return 세트들
    return 세트들.map { it.copy(w = 실제무게(방, it.w, 몸.체중)) }
}

/** 기록의 세트들 → 세션 입력값 ([실제세트들] 의 거꾸로). 플랜 줄은 그대로 */
fun 앱데이터.입력세트들(종id: String?, 이름: String, 플랜id: String?, 세트들: List<세트>): List<세트> {
    if (플랜id != null || 세트들.isEmpty()) return 세트들
    val 방 = 방식(종id, 이름)
    if (방 != 기록방식.맨몸 && 방 != 기록방식.어시스트) return 세트들
    return 세트들.map { it.copy(w = 입력무게(방, it.w, 몸.체중)) }
}

/**
 * 근육 피로 계산용 맨몸 비율 (10-12 홍겸 님) — 맨몸 세트는 체중 전부가 아니라 **그 종목이 실제로 드는 비율**만큼 센다.
 * 플랜 표의 종목별 비율을 그대로 쓴다: 턱걸이 1.00 · 팔굽혀펴기 0.64(Ebben · Wurm 2011) · 맨몸 스쿼트 0.85(Claude 계산, 13 문서 §3).
 * 표에 없는 맨몸 종목은 예전 상수 [근육표.맨몸비율](0.6) — 이 값은 문서에 근거가 없다(임시)
 */
fun 피로맨몸비(이름: String): Double {
    val 대표 = 종목사전.정확히(이름)?.이름 ?: 이름
    return 플랜표.찾기(대표)?.맨몸비?.takeIf { it > 0.0 } ?: 근육표.맨몸비율
}

/**
 * 근육 피로 계산에 넣을 세트들. 저장되는 기록([실제세트들])과 같되, 맨몸은 체중 전부 대신 [피로맨몸비] × 체중 + 추가 kg.
 * 어시스트(체중 − 보조) · 일반 무게 · 플랜 줄은 [실제세트들] 과 같다
 */
fun 앱데이터.피로세트들(종id: String?, 이름: String, 플랜id: String?, 세트들: List<세트>): List<세트> {
    if (플랜id != null || 세트들.isEmpty()) return 세트들
    // 시간(버티기): r 은 초다 → 피로 계산에서는 [회당초] 로 나눠 '횟수 환산'. 무게는 0 (= 체중 × 0.6 으로 센다). 근거 없는 임시 환산
    if (방식(종id, 이름).시간칸()) return 세트들.map { it.copy(w = 0.0, r = max(1, (it.r / 회당초.toDouble()).roundToInt())) }
    if (방식(종id, 이름) != 기록방식.맨몸 || 몸.체중 <= 0.0) return 실제세트들(종id, 이름, 플랜id, 세트들)
    val 비 = 피로맨몸비(종목찾기(종id, 이름)?.이름 ?: 이름)
    return 세트들.map { it.copy(w = 무게반올림(몸.체중 * 비 + it.w)) }
}

/** 운동 중 볼륨 — 체크한 세트, 실제 무게로 (운동 화면 맨 위 띠 · 저장되는 기록의 볼륨과 같은 값) */
fun 앱데이터.운동중볼륨(S: 운동세션): Double =
    S.종목들.sumOf { e -> 볼륨(실제세트들(e.종id, e.이름, e.플랜id, e.찬것())) }

/** 운동 중 목표 볼륨 — 칸마다 보이는 값(기록 · 고친 값 · 기본값), 실제 무게로 */
fun 앱데이터.운동중목표볼륨(S: 운동세션): Double =
    S.종목들.sumOf { e -> 볼륨(실제세트들(e.종id, e.이름, e.플랜id, (0 until e.총칸()).map { k -> S.세트값(e, k) })) }
