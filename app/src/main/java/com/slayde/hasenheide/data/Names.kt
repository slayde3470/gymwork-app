    /** 글자를 자음·모음으로 풀고, 띄어쓰기를 뺀다. 영문은 소문자로 */
    fun 자모(글: String): String {
        val b = StringBuilder()
        for (ch in 글) {
            when {
                ch.isWhitespace() -> {}
                ch in '가'..'힣' -> {
                    val n = ch - '가'
                    b.append(초성[n / 588]).append(중성[(n % 588) / 28]).append(종성[n % 28])
                }
                겹.containsKey(ch) -> b.append(겹.getValue(ch))
                else -> b.append(ch.lowercaseChar())
            }
        }
        return b.toString()
    }

    /**
     * 추천 — 친 글이 들어 있는 이름들. 앞에서부터 맞는 것 → 중간에 맞는 것, 짧은 것 먼저.
     * 친 글과 똑같은 이름 하나뿐이면 추천하지 않는다(이미 다 쳤으니까).
     */
    fun 찾기(입력: String, 후보: List<String>, 최대: Int = 6): List<String> {
        val q = 자모(입력)
        if (q.isEmpty()) return emptyList()
        val 결과 = 후보.distinct().mapNotNull { n ->
            val j = 자모(n)
            val at = j.indexOf(q)
            if (at < 0) null else Triple(n, if (at == 0) 0 else 1, j.length)
        }.sortedWith(compareBy({ it.second }, { it.third })).map { it.first }.take(최대)
        return if (결과.size == 1 && 자모(결과[0]) == q) emptyList() else 결과
    }
