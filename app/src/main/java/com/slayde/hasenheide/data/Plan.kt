/** 무게를 원판 단위로 맞춘다 — 설정의 무게폭(기본 1kg)을 쓴다 */
fun 무게맞춤(kg: Double, 폭: Double = 1.0): Double {
    if (폭 <= 0) return kg
    return (kg / 폭).roundToInt() * 폭
}

/** 1RM ÷ 체중 으로 수준을 판정한다 */
fun 수준판정(표: 플랜종목, 일RM값: Double, 몸: 몸조건): 수준 {
    if (몸.체중 <= 0) return 수준.입문
    val 비 = 일RM값 / 몸.체중
    val 경계 = if (몸.남) 표.경계남 else 표.경계여
    return when {
        비 < 경계[0] -> 수준.입문
        비 < 경계[1] -> 수준.초급
        비 < 경계[2] -> 수준.중급
        비 < 경계[3] -> 수준.고급
        else -> 수준.상급
    }
}

/**
 * 4주당 기대 향상률(%) — 표의 기준값 × 종목배수 × 속도배수 × 나이 × 성별.
 * 상한: 기준값 × 종목배수 × `상한배수` 를 넘지 않는다.
 */
fun 기대속도(표: 플랜종목, 수준값: 수준, 속도값: 속도, 몸: 몸조건): Double {
    // 표에 없으면 가장 느린 값으로 — 표는 다섯 단계를 모두 채우고 있으므로 닿지 않는 길이다
    val 바탕 = (플랜표.기준속도[수준값] ?: 플랜표.기준속도.getValue(수준.상급)) * 표.속도배수
    val 값 = 바탕 * 속도값.배수 * 플랜표.나이배수(몸.나이) * 플랜표.성별배수
    return min(값, 바탕 * 플랜표.상한배수)
}

/**
 * 목표까지 몇 주 걸릴까.
 *
 * 수준이 오르면 속도가 떨어지므로 **한 주씩 밟아 가며** 센다 (한 번에 나누지 않는다).
 * 근거가 가장 약한 부분이다 (12 문서 '한계') → 측정일마다 다시 계산해 맞춰 간다.
 *
 * @return 걸리는 주 수. 너무 멀면 [최대주] 를 돌려준다
 */
fun 남은주(표: 플랜종목, 지금1RM: Double, 목표1RM: Double, 속도값: 속도, 몸: 몸조건, 최대주: Int = 플랜표.최대주): Int {
    if (지금1RM <= 0.0 || 목표1RM <= 지금1RM) return 0
    var 값 = 지금1RM
    var 주 = 0
    while (값 < 목표1RM && 주 < 최대주) {
        val 수준값 = 수준판정(표, 값, 몸)
        val 넉주 = 기대속도(표, 수준값, 속도값, 몸)
        if (넉주 <= 0.0) return 최대주
        // 4주당 %를 한 주당으로 — 복리로 쪼갠다
        val 한주 = (1.0 + 넉주 / 100.0).pow(0.25)
        값 *= 한주
        주++
    }
    return 주
}

/** 몇 주째의 목표 1RM — 남은주()와 같은 걸음으로 앞으로 걸어간다 */
fun 주목표1RM(표: 플랜종목, 시작1RM: Double, 주: Int, 속도값: 속도, 몸: 몸조건): Double {
    var 값 = 시작1RM
    repeat(max(0, 주 - 1)) {
        val 수준값 = 수준판정(표, 값, 몸)
        val 넉주 = 기대속도(표, 수준값, 속도값, 몸)
        값 *= (1.0 + 넉주 / 100.0).pow(0.25)
    }
    return 값
}

/**
 * 그 주의 처방을 낸다 (13-1 7번 '꾸준히 늘리기').
 *
 * 목표 1RM 에서 그 종목 목표 횟수로 들 수 있는 무게를 에플리로 되돌리고,
 * 실제로는 그 무게의 [플랜표.처방비율] 만큼만 올린다 (마지막 한 세트까지 채울 수 있게).
 */
fun 주처방내기(표: 플랜종목, 플랜값: 플랜, 주: Int, 몸: 몸조건, 무게폭: Double = 1.0): 주처방 {
    // 09-29 고침: 측정일 기록이 있으면 그 값 · 그 주를 출발점으로 삼는다.
    // 전에는 늘 시작값에서 걸어와, 측정일 결과가 처방에 전혀 반영되지 않았다 (12 문서 4번 요구사항).
    val 걸을주 = (주 - 플랜값.기준주 + 1).coerceAtLeast(1)
    val 목표 = 주목표1RM(표, 플랜값.지금1RM, 걸을주, 플랜값.속도단계, 몸)
    val 횟수 = 표.목표.횟수.coerceIn(플랜표.횟수범위.first, 플랜표.횟수범위.last)
    // 에플리 뒤집기: 1RM = w(1 + r/30) → w = 1RM / (1 + r/30)
    val 무게 = 무게맞춤(목표 / (1 + 횟수 / 30.0) * 플랜표.처방비율, 무게폭)
    val 수준값 = 수준판정(표, 목표, 몸)
    val 주기 = 플랜표.측정주기[수준값] ?: 12
    return 주처방(주, 목표, 무게, 횟수, 플랜표.기본세트, 측정일 = 주 % 주기 == 0)
}

/**
 * 측정일 결과로 남은 주를 다시 잡는다 (13-1 9번).
 *
 * @return (새 남은 주, 그 주를 반복할까)
 */
fun 측정일조정(표: 플랜종목, 측정값: 측정, 계획1RM: Double, 목표1RM: Double, 속도값: 속도, 몸: 몸조건): Pair<Int, Boolean> {
    val 실제 = 측정값.환산1RM
    val 남 = 남은주(표, 실제, 목표1RM, 속도값, 몸)
    // 2.5kg 안쪽이면 계획 그대로
    if (kotlin.math.abs(실제 - 계획1RM) <= 플랜표.그대로폭) return 남 to false
    val 달성비 = if (계획1RM > 0) 실제 / 계획1RM else 1.0
    val 조정 = 달성비.coerceIn(플랜표.조정하한, 플랜표.조정상한)
    // 계획보다 낮으면 남은 주가 늘어난다 (조정 < 1 → 나누면 커진다)
    val 새남은 = ceil(남 / 조정).toInt()
    return 새남은 to (달성비 < 플랜표.반복선)
}

/**
 * 오늘이 몇 주차인가 — 만든 날로부터 지난 주를 센다 (1부터).
 *
 * 09-29 고침: 전에는 `플랜.지금주` 가 저절로 오르지 않아 늘 1주차 처방만 나왔다.
 * 날짜로 세면 앱을 며칠 안 켜도 주차가 맞는다.
 * 만든날이 비어 있거나 읽을 수 없으면 저장된 `지금주` 를 그대로 쓴다.
 */
fun 플랜.주차(오늘: String): Int {
    if (만든날.isBlank()) return 지금주
    return try {
        val a = java.time.LocalDate.parse(만든날)
        val b = java.time.LocalDate.parse(오늘)
        val 일 = java.time.temporal.ChronoUnit.DAYS.between(a, b)
        if (일 < 0) 지금주 else (일 / 7 + 1).toInt()
    } catch (e: Exception) { 지금주 }
}

/** 같은 날 함께 두면 안 되는 종목인가 */
fun 같은날안됨(a: String, b: String): Boolean =
    플랜표.찾기(a)?.다른날?.contains(b) == true || 플랜표.찾기(b)?.다른날?.contains(a) == true

