/** 그 주의 처방 — 화면과 루틴에 그대로 들어간다 */
data class 주처방(
    val 주: Int,
    val 목표1RM: Double,
    /** 세트에 올릴 무게 (무게폭으로 반올림한 값) */
    val 무게: Double,
    val 횟수: Int,
    val 세트: Int,
    /** 이 주가 측정일인가 */
    val 측정일: Boolean,
