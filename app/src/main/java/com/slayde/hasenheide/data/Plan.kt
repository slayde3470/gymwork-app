/** 사람 조건 — 플랜 계산에 쓰는 것만 */
data class 몸조건(val 나이: Int = 35, val 남: Boolean = true, val 체중: Double = 70.0)

/** 한 종목의 플랜 — 앱에 저장된다 */
data class 플랜(
    val 종목: String,
    /** 시작할 때 잰 값 (무게 × 횟수) */
    val 시작무게: Double,
    val 시작횟수: Int,
    val 속도단계: 속도 = 속도.보통,
    /** 만든 날 "2026-09-28" */
    val 만든날: String = "",
    /** 지금 몇 주째인가 (1부터) */
    val 지금주: Int = 1,
    /** 측정일마다 남긴 기록 */
    val 측정들: List<측정> = emptyList(),
    /** 켜져 있으면 루틴에 처방이 들어간다 */
    val 켬: Boolean = true,
) {
    val 시작1RM: Double get() = 일RM(시작무게, 시작횟수)

    /** 가장 최근 측정 — 없으면 null */
    val 마지막측정: 측정? get() = 측정들.maxByOrNull { it.주 }

    /**
     * 지금 실력으로 보는 1RM.
     * 측정일 기록이 있으면 **그 값**을, 없으면 시작값을 쓴다.
     * (09-29 고침: 전에는 늘 시작값만 보아 측정을 해도 화면이 바뀌지 않았다)
     */
    val 지금1RM: Double get() = 마지막측정?.환산1RM ?: 시작1RM

    /** 계산을 시작할 주 — 마지막 측정을 한 주부터 (측정이 없으면 1주차부터) */
    val 기준주: Int get() = 마지막측정?.주 ?: 1
}

