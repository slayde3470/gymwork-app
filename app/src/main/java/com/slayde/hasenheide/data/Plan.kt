/** 사람 조건 — 나이나 체중이 0 이면 '아직 안 넣음' 으로 본다 */
data class 몸조건(val 나이: Int = 0, val 남: Boolean = true, val 체중: Double = 0.0) {
    val 찼나: Boolean get() = 나이 > 0 && 체중 > 0
}

/**
 * ★ 향상 데이터 한 줄 (21 문서 5절 · 홍겸 님 09-30 요청).
 *
 * 3절 속도표는 Claude 가 역산한 추측이다. 그래서 **측정할 때마다 한 줄 쌓아 두고**,
 * [플랜표.학습최소] 개 이상 모이면 기본표 대신 홍겸 님 실제 값을 쓴다.
 * **맨몸 3종만이 아니라 3대·모든 플랜 종목에 같이 쌓는다** (데이터를 한곳에 모으려고).
 * 백업 내보내기에 들어간다 → 파일만 주면 표를 다시 짤 수 있다.
 */
data class 향상기록(
    val 날짜: String,
    /** 종목 이름 (플랜 이름이 아니라 바탕 종목) */
    val 종목: String,
    /** 측정값 — 무게 종목은 환산 1RM(kg), 맨몸은 정자세 최대 횟수 */
    val 측정값: Double,
    val 체중: Double,
    /** 어시스트·과부하를 반영한 그날 유효 부하(kg). 무게 종목은 0 */
    val 유효부하: Double = 0.0,
    /** 직전 측정 이후 그 종목을 한 총 반복 수 */
    val 누적횟수: Int = 0,
    /** 그 사이 그 종목을 한 날 수 */
    val 운동일수: Int = 0,
    /** 앱이 예상했던 값 */
    val 예상값: Double = 0.0,
) {
    /** 실제 ÷ 예상. 1.0 보다 크면 예상보다 잘 늘었다 */
    val 오차: Double get() = if (예상값 > 0) 측정값 / 예상값 else 0.0
}

/**
 * 내 기록으로 속도표를 보정하는 배수 (21 문서 5절).
 * @return null 이면 아직 기본표를 쓴다 (측정이 [플랜표.학습최소] 개 미만)
 */
fun 보정배수(기록들: List<향상기록>, 종목: String): Double? {
    val 것 = 기록들.filter { it.종목 == 종목 && it.예상값 > 0 && it.측정값 > 0 }
    if (것.size < 플랜표.학습최소) return null
    return 것.map { it.오차 }.average().coerceIn(0.5, 2.0)
}

/** 화면에 지금 무엇을 쓰는지 보이는 글 (21 문서 5절) */
fun 속도출처글(기록들: List<향상기록>, 종목: String): String {
    val n = 기록들.count { it.종목 == 종목 && it.예상값 > 0 && it.측정값 > 0 }
    return if (n >= 플랜표.학습최소) "내 기록 (${n}회)" else "기본표"
}

