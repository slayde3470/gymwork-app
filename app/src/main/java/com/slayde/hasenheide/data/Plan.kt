    /** 맨몸 유효 부하 비율 — 0 이면 바벨·머신(체중과 무관). 턱걸이 1.00 · 팔굽 0.64 · 스쿼트 0.85 (21 문서 1절) */
    val 맨몸비: Double = 0.0,
    /** 진행을 무게로 올리나 횟수로 올리나 (21 문서 0절) */
    val 진행: 진행기준 = 진행기준.무게,
    /** 목표를 적는 기본 단위 */
    val 기본단위: 목표단위 = 목표단위.무게,
    /** 횟수로 진행하는 종목의 수준 경계 — **정자세 최대 연속 횟수** (21 문서 2절) */
