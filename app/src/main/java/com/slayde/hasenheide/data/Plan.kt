/** 수준 5단계 */
enum class 수준(val 이름: String) { 입문("입문"), 초급("초급"), 중급("중급"), 고급("고급"), 상급("상급") }

/** 빈도 효과가 부위마다 다르다 (20 문서 A-2) */
enum class 부위(val 이름: String, val 빈도세기: Double) { 상체("상체", 1.0), 하체("하체", 0.2) }

/** 목표를 적는 형식 — 계산은 둘 다 같다. 표시만 다르다 (20 문서 C-1) */
enum class 목표형식(val 이름: String) { RM("1RM"), 무게횟수("무게 × 횟수") }

/**
 * 목표를 적는 단위 (21 문서 0절 · 홍겸 님 09-30).
 * 맨몸은 무게가 고정이라 무게로 목표를 적을 수 없다 → 개수·시간·거리.
 * **"500개" 는 한 번에 연속 500개를 뜻한다.**
 */
enum class 목표단위(val 이름: String, val 단위: String) {
    무게("무게", "kg"), 개수("개수", "개"), 시간("시간", "초"), 거리("거리", "m"),
}

/** 진행을 무엇으로 올리나 — 3대는 무게, 맨몸 3종은 횟수 (21 문서 0절) */
enum class 진행기준 { 무게, 횟수 }

/** 세트 종류 — 워밍업·측정은 볼륨에서 뺀다 (20 문서 B-5, 홍겸 님 09-29 확정) */
object 세트종류 { const val 본운동 = 0; const val 워밍업 = 1; const val 측정 = 2 }

/**
