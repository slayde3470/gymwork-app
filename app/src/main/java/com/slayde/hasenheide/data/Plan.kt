    /** 목표를 적는 단위. 맨몸은 개수·시간·거리 (21 문서 0절) */
    val 단위: 목표단위 = 목표단위.무게,
    /** 맨몸 목표 — 개수(회) · 시간(초) · 거리(m). "500개" = 한 번에 연속 500개 */
    val 목표개수: Double = 0.0,
    /** 맨몸 시작값 (같은 단위) */
    val 시작개수: Double = 0.0,
    /** 턱걸이 보조 — 0 정자세 · 1 어시스트 · 2 과부하 (21 문서 4절) */
    val 보조모드: Int = 0,
    /** 어시스트 보조 무게 또는 과부하 추가 무게(kg) */
    val 보조무게: Double = 0.0,
    val 만든날: String = "",
    /** 실제로 마친 회차 */
    val 한회: Int = 0,
    /** 마친 회차의 볼륨 합 (워밍업·측정 뺀 것) */
    val 누적볼륨: Double = 0.0,
    val 측정들: List<측정> = emptyList(),
    /** 보통 날 워밍업 세트 수 — 0 이면 붙이지 않는다 (beta) */
    val 워밍업수: Int = 0,
    val 켬: Boolean = true,
) {
    val 표: 플랜종목? get() = 플랜표.찾기(종목)
    val 목표1RM: Double get() = if (목표방식 == 목표형식.RM) 목표무게 else 일RM(목표무게, 목표횟수)
    val 목표글: String get() = if (목표방식 == 목표형식.RM) "1RM ${무게글(목표무게)}kg" else "${무게글(목표무게)}kg × ${목표횟수}회"
    val 마지막측정: 측정? get() = 측정들.maxByOrNull { it.회 }
    /** 지금 실력 — 측정 기록이 있으면 그 값, 없으면 시작값 */
    val 지금1RM: Double get() = 마지막측정?.환산1RM ?: 시작1RM
    /** 계산을 시작할 회 — 마지막 측정을 한 회부터 */
    val 기준회: Int get() = 마지막측정?.회 ?: 0

    // ── 맨몸 3종 (21 문서) ──
    /** 횟수로 진행하는 종목인가 */
    val 횟수진행: Boolean get() = 표?.횟수진행 == true
    /**
     * 진행 변수의 목표값 — 무게 종목은 1RM(kg), 맨몸은 횟수·초·m.
     * 맨몸은 **늘 정자세 기준**이다 (어시스트를 써도 목표는 안 바뀐다, 21 문서 4절).
     */
    val 목표진행값: Double get() = if (횟수진행) 목표개수 else 목표1RM
    /**
     * 진행 변수의 시작값. 맨몸은 1 미만을 1 로 본다 —
     * 곱셈으로 늘리기 때문에 0 에서는 영원히 늘지 않는다.
     * (홍겸 님 턱걸이는 지금 정자세 1회 미만이다 → 1회를 시작점으로 잡는다)
     */
    val 시작진행값: Double get() = if (횟수진행) max(1.0, 시작개수) else 시작1RM
    /** 지금 실력 — 측정 기록이 있으면 그 값 */
    val 지금진행값: Double get() =
        if (횟수진행) max(1.0, 마지막측정?.횟수?.toDouble() ?: 시작개수) else 지금1RM
    /** 맨몸 목표 글 — "500개" · "60초" · "1000m" */
    val 맨몸목표글: String get() = "${무게글(목표개수)}${단위.단위}"
}

/**
 * 한 회차의 계획.
 * [목표값] 은 무게 종목이면 1RM(kg), 맨몸 종목이면 그 회차에 노리는 **횟수**다 (21 문서 0절).
 */
data class 회계획(val 회: Int, val 주: Int, val 목표값: Double, val 수준값: 수준, val 측정일: Boolean) {
    /** 옛 이름 — 무게 종목에서 쓰던 것 */
    val 목표1RM: Double get() = 목표값
}

/** 무게를 원판 단위로 맞춘다 — 설정의 무게폭(기본 1kg) */
fun 무게맞춤(kg: Double, 폭: Double = 1.0): Double {
    if (폭 <= 0) return kg
    return max(폭, (kg / 폭).roundToInt() * 폭)
}

/** 1RM ÷ 체중 으로 수준을 판정한다 */
fun 수준판정(표: 플랜종목, 일RM값: Double, 몸: 몸조건): 수준 {
    if (몸.체중 <= 0) return 수준.입문
    val 비 = 일RM값 / 몸.체중
    val 경계 = if (몸.남) 표.경계남 else 표.경계여
    return when {
        비 < 경계[0] -> 수준.입문
        비 < 경계[1] -> 수준.초급
        비 < 경계[2] -> 수준.중급
        비 < 경계[3] -> 수준.고급
        else -> 수준.상급
    }
}

/**
 * 횟수로 진행하는 종목의 수준 판정 — **정자세 최대 연속 횟수** 로 본다 (21 문서 2절).
 * 체중과 무관하다 (표 자체가 체중 109kg 남 기준으로 만들어졌다).
 */
fun 수준판정횟수(표: 플랜종목, 횟수: Double): 수준 {
    val 경계 = 표.횟수경계
    if (경계.size < 4) return 수준.입문
    return when {
        횟수 < 경계[0] -> 수준.입문
        횟수 < 경계[1] -> 수준.초급
        횟수 < 경계[2] -> 수준.중급
        횟수 < 경계[3] -> 수준.고급
        else -> 수준.상급
    }
}

/** 종목이 무엇이든 그 진행값의 수준 */
fun 수준보기(표: 플랜종목, 진행값: Double, 몸: 몸조건): 수준 =
    if (표.횟수진행) 수준판정횟수(표, 진행값) else 수준판정(표, 진행값, 몸)

/**
 * 맨몸 유효 부하(kg) — 볼륨 계산과 어시스트 환산에 쓴다 (21 문서 1절).
 * @param 조절 어시스트는 음수(−보조), 과부하는 양수(+추가). 정자세는 0
 */
fun 플랜종목.유효부하(체중: Double, 조절: Double = 0.0): Double =
    if (!맨몸인가) 0.0 else max(1.0, 체중 * 맨몸비 + 조절)

/**
 * 어시스트·과부하에서 오늘 할 횟수 — **에플리를 뒤집은 것** (21 문서 4절).
 *
 * 에플리: `1RM = w × (1 + r/30)` → `r = 30 × (1RM/w − 1)`
 * 보조를 줄이면 유효 부하 w 가 올라가 이 횟수가 저절로 줄고, 그게 진도다.
 *
 * ⚠ r = 1 은 에플리가 1RM 자체로 특별 취급하므로(일RM 참고) 이 식은 0 을 낸다.
 */
fun 어시스트횟수(목표1RM: Double, 유효부하: Double): Double =
    if (유효부하 <= 0) 0.0 else 30.0 * (목표1RM / 유효부하 - 1.0)

/** 보조모드(0 정자세 · 1 어시스트 · 2 과부하)를 부호 있는 조절값으로 */
fun 보조조절(보조모드: Int, 보조무게: Double): Double = when (보조모드) {
    1 -> -보조무게
    2 -> +보조무게
    else -> 0.0
}

/**
 * 빈도 포화 곡선 — 주당 횟수를 늘리면 좋아지지만 곧 멈춘다 (20 문서 A-1).
 * 주2회에서 정확히 1.00 이라, 지금까지 합의한 주수가 그대로 이어진다.
 */
fun 포화(f: Int): Double = (1.0 - exp(-f / 2.0)) / (1.0 - exp(-1.0))

/** 부위마다 빈도 효과가 다르다 — 상체 1.0 · 하체 0.2 (홍겸 님 09-29 확정) */
fun 빈도배수(f: Int, 부위값: 부위): Double = 1.0 + 부위값.빈도세기 * (포화(f) - 1.0)

/**
 * 4주당 기대 향상률(%).
 *  · 종목 전용 [플랜종목.속도표] 가 있으면 그것을 쓴다 (맨몸 3종 — 21 문서 3절).
 *    그 값은 **절대값**이라 `속도배수` 를 곱하지 않는다.
 *  · 없으면 예전대로 `기준속도 × 속도배수` (3대 · OHP · 로우)
 *  · [보정] 은 내 기록으로 배운 배수 (21 문서 5절). 1.0 이면 기본표 그대로
 */
fun 기대속도(표: 플랜종목, 수준값: 수준, 몸: 몸조건, 주당: Int, 보정: Double = 1.0): Double {
    val 바탕 = 표.속도표[수준값]
        ?: ((플랜표.기준속도[수준값] ?: 플랜표.기준속도.getValue(수준.상급)) * 표.속도배수)
    return 바탕 * 플랜표.나이배수(몸.나이) * 빈도배수(주당, 표.부위값) * 보정
}

/**
 * 목표까지의 회차표를 만든다. **측정일도 한 회다** — 그날도 본 운동을 그대로 한다.
 *
 * 4주당 기대 %를 한 회당으로 쪼갠다: 4주 = 4 × 주당 회수.
 */
fun 회표(
    표: 플랜종목,
    시작값: Double,
    목표값: Double,
    주당: Int,
    몸: 몸조건,
    최대: Int = 플랜표.최대회,
    보정: Double = 1.0,
): List<회계획> {
    val out = ArrayList<회계획>()
    if (시작값 <= 0.0 || 목표값 <= 시작값 || 주당 <= 0) return out
    var 값 = 시작값
    var n = 0
    while (값 < 목표값 && n < 최대) {
        n++
        val 수준값 = 수준보기(표, 값, 몸)
        val 넉주 = 기대속도(표, 수준값, 몸, 주당, 보정)
        if (넉주 <= 0.0) break
        값 *= (1.0 + 넉주 / 100.0).pow(1.0 / (4.0 * 주당))
        val 간격 = max(1, ((플랜표.측정주기[수준값] ?: 12) * 주당))
        out.add(회계획(n, ceil(n / 주당.toDouble()).toInt(), 값, 수준값, n % 간격 == 0))
    }
    return out
}

/**
 * 플랜 하나의 회차표 — 마지막 측정 이후부터 다시 걸어간다.
 * 맨몸 종목이면 진행 변수가 **횟수**다 (21 문서 0절).
 * @param 기록들 향상기록. 3개 이상 쌓이면 내 값으로 속도를 보정한다 (21 문서 5절)
 */
fun 플랜.회표(몸: 몸조건, 기록들: List<향상기록> = emptyList()): List<회계획> {
    val t = 표 ?: return emptyList()
    val 보정 = 보정배수(기록들, 종목) ?: 1.0
    return 회표(t, 지금진행값, 목표진행값, 주당, 몸, 플랜표.최대회, 보정)
}

/**
 * 맨몸 종목의 그 회차 처방 (21 문서 6절).
 *  · 보통 날 — 그 회차 목표 최대치의 50% × 5세트
 *  · 측정일 — 1세트 최대 (워밍업은 측정일만 자동, v0.9.0 규칙 그대로)
 *  · 턱걸이 어시스트·과부하 — 처방 횟수 = `30 × (목표1RM ÷ 유효부하 − 1)`, **5~10회로 제한**
 *    (에플리를 뒤집은 것. 12회를 넘으면 오차가 커져서 자른다 — 21 문서 4절)
 *
 * 무게 칸에는 **유효 부하**를 넣는다 → 볼륨이 맞게 쌓인다.
 */
fun 맨몸처방(플랜값: 플랜, 목표횟수값: Double, 몸: 몸조건, 측정일: Boolean = false): List<세트처방> {
    val t = 플랜값.표 ?: return emptyList()
    val 조절 = 보조조절(플랜값.보조모드, 플랜값.보조무게)
    val 정자세부하 = t.유효부하(몸.체중)
    val 부하 = t.유효부하(몸.체중, if (t.보조옵션) 조절 else 0.0)
    if (측정일) return listOf(세트처방(정자세부하, max(1.0, 목표횟수값).roundToInt(), 1, "측정"))

    // 어시스트·과부하 — 목표 1RM 을 유효 부하로 나눠 오늘 횟수를 뒤집어 낸다
    if (t.보조옵션 && 플랜값.보조모드 != 0 && 부하 > 0) {
        val 목표1RM값 = 정자세부하 * (1 + 목표횟수값 / 30.0)
        val 횟수 = 어시스트횟수(목표1RM값, 부하)
            .coerceIn(플랜표.어시스트하한.toDouble(), 플랜표.어시스트상한.toDouble())
        val 라벨 = if (플랜값.보조모드 == 1) "어시스트 ${무게글(플랜값.보조무게)}kg" else "과부하 +${무게글(플랜값.보조무게)}kg"
        return listOf(세트처방(부하, 횟수.roundToInt(), 플랜표.맨몸세트, 라벨))
    }
    val 보통 = max(1.0, 목표횟수값 * 플랜표.맨몸보통비).roundToInt()
    return listOf(세트처방(부하, 보통, 플랜표.맨몸세트))
}

/**
 * 그 회차의 세트 처방 — 훈련 방식이 정한다. 무게는 원판 단위로 맞춘다.
 *
 * 1번 방식은 [플랜.세트수] · [플랜.직접횟수] 를 정해 두었으면 그것을 쓴다 (홍겸 님 09-30).
 * **횟수에 상한을 두지 않는다.**
 */
fun 회처방(플랜값: 플랜, 목표값: Double, 무게폭: Double = 1.0, 몸: 몸조건 = 몸조건(), 측정일: Boolean = false): List<세트처방> {
    if (플랜값.횟수진행) return 맨몸처방(플랜값, 목표값, 몸, 측정일)
    val 기본 = 방식찾기(플랜값.방식번호).세트(목표값, 플랜값.강도)
    val 목 = if (플랜값.방식번호 == 1 && (플랜값.세트수 > 0 || 플랜값.직접횟수 > 0)) {
        val s = 강도들.getOrElse(플랜값.강도) { 강도들[1] }
        val 세트 = if (플랜값.세트수 > 0) 플랜값.세트수 else s.세트
        val 횟수 = if (플랜값.직접횟수 > 0) 플랜값.직접횟수 else s.횟수
        listOf(세트처방(되ep(목표값, 횟수) * 플랜표.처방비율, 횟수, 세트))
    } else 기본
    return 목.map { it.copy(무게 = 무게맞춤(it.무게, 무게폭)) }
}

/** 처방 한 줄 글 — "52kg × 12회 × 3세트" 또는 "월 52×5×5 / 수 44×5×4" */
fun 처방글(목: List<세트처방>): String =
    if (목.size == 1) "${무게글(목[0].무게)}kg × ${목[0].횟수}${if (목[0].더하기) "+" else ""}회 × ${목[0].세트}세트"
    else 목.joinToString(" / ") { "${if (it.라벨.isNotEmpty()) it.라벨 + " " else ""}${무게글(it.무게)}×${it.횟수}${if (it.더하기) "+" else ""}×${it.세트}" }

/** 측정일 워밍업 — 본 무게 기준 (총 9회) */
fun 측정워밍업(본무게: Double, 무게폭: Double = 1.0): List<세트처방> =
    플랜표.측정워밍업비.map { (p, r) -> 세트처방(무게맞춤(본무게 * p, 무게폭), r, 1) }

/** 보통 날 워밍업 — 사용자가 켰을 때만 (beta). n 이 0 이면 빈 목록 */
fun 보통워밍업(본무게: Double, n: Int, 무게폭: Double = 1.0): List<세트처방> =
    (플랜표.보통워밍업비[n] ?: emptyList()).map { (p, r) -> 세트처방(무게맞춤(본무게 * p, 무게폭), r, 1) }

/**
 * 측정일 결과로 남은 회차를 다시 잡는다 (13-1 9번).
 * @return (새 남은 회, 그 회를 반복할까)
 */
fun 측정일조정(표: 플랜종목, 측정값: 측정, 계획1RM: Double, 목표1RM: Double, 주당: Int, 몸: 몸조건): Pair<Int, Boolean> {
    // 맨몸 종목은 진행 변수가 횟수다 — 환산하지 않고 그 횟수를 그대로 쓴다 (21 문서 0절)
    val 실제 = if (표.횟수진행) 측정값.횟수.toDouble() else 측정값.환산1RM
    val 남 = 회표(표, 실제, 목표1RM, 주당, 몸).size
    if (abs(실제 - 계획1RM) <= (if (표.횟수진행) 0.5 else 플랜표.그대로폭)) return 남 to false
    val 달성비 = if (계획1RM > 0) 실제 / 계획1RM else 1.0
    val 조정 = 달성비.coerceIn(플랜표.조정하한, 플랜표.조정상한)
    return ceil(남 / 조정).toInt() to (달성비 < 플랜표.반복선)
}

/**
 * 달성률 — 달력으로 지난 주만큼 회차가 따라오고 있나 (홍겸 님 09-29).
 * 지키거나 앞당기면 100%. 50% 면 두 배 오래 걸리는 중.
 */
fun 달성률(한회: Int, 지난주: Int, 주당: Int): Int {
    val 기대 = max(1, 지난주 * 주당)
    return (한회.toDouble() / 기대 * 100).roundToInt().coerceIn(0, 100)
}

/** 만든 날로부터 지난 주 (1부터) */
fun 플랜.지난주(오늘: String): Int {
    if (만든날.isBlank()) return 1
    return try {
        val a = java.time.LocalDate.parse(만든날)
        val b = java.time.LocalDate.parse(오늘)
        val 일 = java.time.temporal.ChronoUnit.DAYS.between(a, b)
        if (일 < 0) 1 else (일 / 7 + 1).toInt()
    } catch (e: Exception) { 1 }
}

/**
 * 측정 결과로 향상기록 한 줄을 만든다 (21 문서 5절).
 * @param 계획값 그 회차에 앱이 예상했던 값 (무게 종목은 1RM, 맨몸은 횟수)
 */
fun 향상한줄(플랜값: 플랜, 측정값: 측정, 계획값: Double, 몸: 몸조건, 누적횟수: Int = 0, 운동일수: Int = 0): 향상기록 {
    val t = 플랜값.표
    val 부하 = if (t != null && t.맨몸인가)
        t.유효부하(몸.체중, if (t.보조옵션) 보조조절(플랜값.보조모드, 플랜값.보조무게) else 0.0) else 0.0
    return 향상기록(
        날짜 = 측정값.날,
        종목 = 플랜값.종목,
        측정값 = if (플랜값.횟수진행) 측정값.횟수.toDouble() else 측정값.환산1RM,
        체중 = 몸.체중,
        유효부하 = 부하,
        누적횟수 = 누적횟수,
        운동일수 = 운동일수,
        예상값 = 계획값,
    )
}

/** 같은 날 함께 두면 안 되는 종목인가 */
fun 같은날안됨(a: String, b: String): Boolean =
    플랜표.찾기(a)?.다른날?.contains(b) == true || 플랜표.찾기(b)?.다른날?.contains(a) == true

/** 누적 운동량 글 — kg 으로 두다가 10만을 넘으면 t (홍겸 님 09-29) */
fun 운동량글(kg: Double): String = when {
    kg >= 1_000_000 -> "%.1f".format(kg / 1_000_000) + "kt"
    kg >= 100_000 -> "%.1f".format(kg / 1000) + "t"
    else -> 콤마(kg) + "kg"
}

// ─────────────── 참고용 — 무게의존 1RM 식 (01 ㉒ 검토 후보) ───────────────

/**
 * Marzagao 2026 프리프린트의 식 (303,494 세트). **지금은 쓰지 않는다** — 에플리로 통일했다 (14 S3).
 */
fun 일RM무게의존(w: Double, r: Int): Double {
    if (r <= 0 || w <= 0) return 0.0
    if (r == 1) return w
    val k = max(0.5, -2.55 + 4.58 * ln(w))
    return w * (1 + (r - 1).toDouble().pow(0.85) / k)
}
