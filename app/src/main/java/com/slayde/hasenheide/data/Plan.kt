/**
 * 맨몸 '나의 수행능력' 칸에 넣은 값 → 정자세 기준 시작값.
 *
 * 10-01 버그: 어시스트 40kg × 10회를 정자세로 바꾸면 **−4.7회** 가 나온다.
 * 화면이 이것을 "0 이하 = 아직 안 넣음" 으로 보고 막아 플랜을 만들 수 없었다.
 * → 어시스트·과부하로 **값을 제대로 넣었으면** 정자세 1회 미만이어도 1회에서 시작한다.
 *
 * @return 정자세 시작값(1 이상). 아직 덜 넣었으면 null
 */
fun 맨몸시작값(표: 플랜종목, 몸: 몸조건, 보조모드: Int, 정자세: Double, 보조무게: Double, 보조횟수: Double): Double? {
    if (!표.맨몸인가) return null
    if (보조모드 == 0 || !표.보조옵션) return if (정자세 > 0) max(1.0, 정자세) else null
    if (보조무게 <= 0 || 보조횟수 < 1) return null
    val 부하 = 표.유효부하(몸.체중, 보조조절(보조모드, 보조무게))
    if (부하 <= 0) return null
    val r = 어시스트횟수(부하 * (1 + 보조횟수 / 30.0), 표.유효부하(몸.체중))
    return max(1.0, r)
}

/** 어시스트·과부하 입력을 정자세로 바꾼 '날 값' (1 미만·음수도 그대로) — 화면에 '1회 미만' 을 보일 때 쓴다 */
fun 맨몸환산값(표: 플랜종목, 몸: 몸조건, 보조모드: Int, 보조무게: Double, 보조횟수: Double): Double {
    val 부하 = 표.유효부하(몸.체중, 보조조절(보조모드, 보조무게))
    return if (부하 > 0 && 보조횟수 >= 1) 어시스트횟수(부하 * (1 + 보조횟수 / 30.0), 표.유효부하(몸.체중)) else 0.0
}

/** 처방을 세트 하나하나로 펼친다 */
fun 처방세트(목: List<세트처방>): List<세트> = 목.flatMap { x -> List(x.세트) { 세트(x.무게, x.횟수) } }

/**
 * 이번 회차에 **실제로 한 값** — 처방 대신 실제 세트로 진행값을 거꾸로 낸다 (10-01 홍겸 님).
 *
 *  · 세트마다 `실제 1RM 환산 ÷ 처방 1RM 환산` = 비율 — 짝은 **무게가 가장 가까운 처방**.
 *    체크한 세트(워밍업 뺌) 가운데 **잘한 세트를 처방 세트 수만큼** 골라 평균한다
 *  · 무게 종목: 그 회차 목표 1RM × 평균 비율
 *  · 맨몸: 목표 횟수를 정자세 1RM 환산(정 × (1 + 횟수/30))으로 바꿔 비율을 곱하고 다시 횟수로 돌린다
 *  · 처방대로 했으면 비율 1 → 목표값 그대로. 안 한 세트는 세지 않는다 (시간이 없어 덜 한 날은 실력이 아니다)
 *  · 세트를 더 했으면 잘한 n개만 쓰므로 가볍게 더 한 세트가 깎지 않는다
 *  · 무게 종목은 10회 넘는 횟수를 자른다 (13-1 #12). 맨몸은 횟수가 곧 실력이라 자르지 않는다
 */
fun 실제진행값(p: 플랜, 목표값: Double, 처방: List<세트>, 실제: List<세트>, 몸: 몸조건): Double? {
    if (처방.isEmpty() || 목표값 <= 0) return null
    val 비 = 실제.filter { it.종류 != 세트종류.워밍업 && it.r > 0 && it.w > 0 }.mapNotNull { s ->
        // 10-01 감시관: 세트 위치는 저장되지 않는다 → **무게가 가장 가까운 처방**과 견준다
        // (5/3/1 · 매드카우처럼 세트마다 무게가 다른 방식에서 한 세트를 건너뛰어도 짝이 맞게)
        val 목 = 처방.minBy { abs(it.w - s.w) }
        val 분모 = 일RM(목.w, 목.r)
        // 무게 종목: 처방보다 많이 한 횟수는 10회(또는 처방 횟수)까지만 센다 — 에플리가 높은 횟수에서 부풀린다
        // 맨몸은 횟수 자체가 진행값이라 자르지 않는다 (감시관 2차: 더 해도 앞당겨지지 않던 것)
        val r = if (p.횟수진행) s.r else min(s.r, max(목.r, 플랜표.환산최대횟수))
        if (분모 <= 0) null else 일RM(s.w, r) / 분모
    }.sortedDescending().take(처방.size)   // 처방보다 세트를 더 했으면 잘한 세트 n개만 — 가볍게 더 한 세트가 깎지 않게
    if (비.isEmpty()) return null
    val 평균 = 비.average()
    if (!p.횟수진행) return 목표값 * 평균
    val 정 = p.표?.유효부하(몸.체중) ?: return null
    if (정 <= 0) return null
    val rm = 정 * (1 + 목표값 / 30.0) * 평균
    return max(1.0, 30.0 * (rm / 정 - 1))
}

/**
 * 측정일에 **그대로 잰 값** — 무게 종목은 10회 이하 세트의 환산 1RM 최고 (13-1 #12 '10회 넘는 세트는 참고만'),
 * 맨몸은 정자세 이상 부하로 한 세트의 최고 횟수. 해당 세트가 없으면 null
 */
fun 측정날값(p: 플랜, 세트들: List<세트>, 몸: 몸조건): Double? {
    val 본 = 세트들.filter { it.종류 != 세트종류.워밍업 && it.r > 0 }
    if (p.횟수진행) {
        val 정 = p.표?.유효부하(몸.체중) ?: return null
        return 본.filter { it.w >= 정 - 0.01 }.maxOfOrNull { it.r.toDouble() }
    }
    return 본.filter { it.r <= 플랜표.환산최대횟수 }.maxOfOrNull { 일RM(it.w, it.r) }
}

/**
 * 운동을 저장할 때 플랜에 반영한다.
 *
 *  · **플랜id 로 짝짓는다** (10-01 — 이름으로 짝지어 같은 이름의 보통 줄도 회차를 올리던 것)
 *  · 체크한 세트가 있으면 → 한회 + 1 · 누적볼륨 += 그 볼륨
 *  · **보통 날**: 처방과 다르게 했으면(덜 했든 더 했든) 그 회의 **실제 값에서 다시 계산**한다 (`재기준`) —
 *    10-01 홍겸 님 "컨디션이 돌아와서 원래대로 마치면 값이 다시 계산될 거잖아". 처방대로 했으면 계획 그대로
 *  · **측정일**: 측정 = max(그대로 잰 값, 실제 값). 보통 처방 세트만 해도 1RM 이 떨어지지 않는다
 *    (10-01 찾은 문제 3 — 59×10 을 측정으로 잡아 78.7kg 이 되던 것). 향상기록 한 줄
 *  · 반영한 뒤 **루틴의 플랜 줄을 다음 회차 처방으로 다시 채운다**
 */
fun 플랜반영(d: 앱데이터, 종목들: List<종목기록>, 날: String, 조절됨: Boolean = false): 앱데이터 {
    if (d.플랜들.isEmpty()) return d
    var 향 = d.향상기록들
    val 새 = d.플랜들.map { p ->
        val e = 종목들.firstOrNull { it.플랜id == p.id } ?: return@map p
        val 세트들 = e.세트들.filter { it.종류 != 세트종류.워밍업 && it.r > 0 }
        if (세트들.isEmpty()) return@map p
        val 계획 = p.다음회(d.몸, 향)
        val 회 = p.한회 + 1
        var q = p.copy(한회 = 회, 누적볼륨 = p.누적볼륨 + 세트들.sumOf { it.w * it.r })
        if (계획 == null) return@map q
        val 처방 = 처방세트(회처방(p, 계획.목표값, d.설정.무게폭, d.몸, 계획.측정일, 계획.주))
        // '그 날만 조절' 로 일부러 가볍게(무겁게) 한 날은 실력으로 치지 않는다 — 측정일이면 그대로 잰 값만 쓴다
        val 실제 = if (조절됨) null else 실제진행값(p, 계획.목표값, 처방, 세트들, d.몸)
        if (계획.측정일) {
            val 값 = max(측정날값(p, 세트들, d.몸) ?: 0.0, 실제 ?: 0.0)
            if (값 > 0) {
                val 최고 = 세트들.filter { it.r <= 플랜표.환산최대횟수 }.maxByOrNull { 일RM(it.w, it.r) }
                val m = when {
                    p.횟수진행 -> 측정(회, 날, p.표?.유효부하(d.몸.체중) ?: 0.0, max(1, 값.roundToInt()))
                    최고 != null && 일RM(최고.w, 최고.r) >= 값 - 1e-9 -> 측정(회, 날, 최고.w, 최고.r)
                    else -> 측정(회, 날, 값, 1)   // 1회 = 그 값이 곧 1RM
                }
                q = q.copy(측정들 = q.측정들 + m)
                // 10-02 감사: 누적횟수 · 운동일수를 채운다 (21 문서 5절 — 전에는 늘 0)
                val (누, 일) = d.측정사이운동(p, 날, 향)
                향 = 향 + 향상한줄(p, m, 계획.목표값, d.몸, 누, 일)
            }
        } else if (실제 != null && abs(실제 - 계획.목표값) > 1e-6) {
            q = q.copy(재기준 = 재기준점(회, 날, 실제))
        }
        q
    }
    val 바뀐 = d.copy(플랜들 = 새, 향상기록들 = 향)
    return 바뀐.copy(루틴들 = 바뀐.루틴들.map { 바뀐.플랜줄채움(it) })
}

/**
 * 플랜 줄 정리 (10-01 감시관) — 불러올 때 · 플랜을 지울 때.
 *  · 지운 플랜을 가리키는 줄은 보통 줄로 돌린다 (안 그러면 루틴 반영 · 볼륨 올리기에서 빠진 채 얼어붙는다)
 *  · 플랜 줄은 슈퍼세트로 묶지 않는다 (01 ㉓-7) — v0.11 에서 묶인 것을 푼다
 */
fun 앱데이터.플랜줄정리(): 앱데이터 {
    val 있는 = 플랜들.map { it.id }.toSet()
    var 바뀜 = false
    val 새 = 루틴들.map { r ->
        if (r.종목.none { it.플랜id != null }) r
        else {
            val l = r.종목.map { e ->
                when {
                    e.플랜id == null -> e
                    e.플랜id !in 있는 -> { 바뀜 = true; e.copy(플랜id = null) }
                    e.슈퍼 != null -> { 바뀜 = true; e.copy(슈퍼 = null) }
                    else -> e
                }
            }
            r.copy(종목 = l).묶음정리()
        }
    }
    return if (바뀜) copy(루틴들 = 새) else this
}

/**
 * 루틴의 플랜 줄을 **지금 회차 처방**으로 채운다 (10-01 — 넣은 회차 값에 멈춰 있던 것).
 * 운동을 시작할 때 · 플랜에 반영한 뒤 부른다. 휴식은 사용자가 정한 값을 둔다
 */
fun 앱데이터.플랜줄채움(e: 루틴종목): 루틴종목 {
    val id = e.플랜id ?: return e
    val p = 플랜들.firstOrNull { it.id == id } ?: return e
    val 계획 = p.다음회(몸, 향상기록들) ?: return e
    val 값 = 처방세트(회처방(p, 계획.목표값, 설정.무게폭, 몸, 계획.측정일, 계획.주))
    if (값.isEmpty()) return e
    val 휴 = if (p.횟수진행) 플랜표.맨몸휴식 else e.휴식
    return e.copy(이름 = p.이름, 세트 = 값.size, 무게 = 값[0].w, 횟수 = 값[0].r, 휴식 = 휴, 세트값 = 값,
        휴식값 = List(값.size) { k -> e.휴식값.getOrNull(k) ?: 휴 })
}

fun 앱데이터.플랜줄채움(r: 루틴): 루틴 = if (r.종목.none { it.플랜id != null }) r else r.copy(종목 = r.종목.map { 플랜줄채움(it) })

/**
 * 측정일 워밍업 자동 (20 문서 B-3 · B-4 · 2-23 확정 — 10-02 감사에서 빠진 것을 찾아 넣음).
 * 다음 회차가 **측정일인 무게 종목** 플랜 줄의 본 세트 앞에 [측정워밍업] 세트(40/60/90%)를
 * [세트종류.워밍업] 으로 붙인다.
 *  · **운동을 시작할 때만** 붙인다 (조절해시작 · 캘린더 '한 번 더'). 루틴에는 저장하지 않는다 — 루틴 볼륨 · 예상 시간이 부풀지 않게
 *  · 기준 무게 = 그 줄의 첫 본 세트 무게 (그 날만 조절했으면 조절한 무게). 쉬는 시간은 그 줄의 휴식 그대로
 *  · 맨몸 3종은 붙이지 않는다 (B-3: 무게 램프가 뜻이 없다)
 *  · 워밍업 세트는 볼륨(볼륨()) · 1RM(기록세트()) · 플랜 반영(플랜반영)에서 빠진다
 */
fun 앱데이터.측정워밍업붙임(r: 루틴): 루틴 {
    if (r.종목.none { it.플랜id != null }) return r
    return r.copy(종목 = r.종목.map { e ->
        val p = 플랜들.firstOrNull { it.id == e.플랜id } ?: return@map e
        if (p.횟수진행 || p.다음회(몸, 향상기록들)?.측정일 != true) return@map e
        val 본 = (0 until e.세트).map { e.목표(it) }
        if (본.isEmpty() || 본.any { it.종류 == 세트종류.워밍업 }) return@map e   // 이미 붙어 있으면 그대로
        val 웜 = 처방세트(측정워밍업(본[0].w, 설정.무게폭)).map { it.copy(종류 = 세트종류.워밍업) }
        val 휴 = (0 until e.세트).map { e.휴식(it) }
        e.copy(세트 = 웜.size + 본.size, 무게 = 웜[0].w, 횟수 = 웜[0].r, 세트값 = 웜 + 본, 휴식값 = List(웜.size) { e.휴식 } + 휴)
    })
}

/**
 * '지금 수행능력 다시 입력' — 측정일이 아니어도 언제든 (20 문서 C-2 · 10-01).
 * 오래 쉬었거나 생각보다 빨리 늘었을 때. 회차표는 이 값에서 다시 걸어간다.
 */
fun 플랜.측정넣기(날: String, 무게: Double, 횟수: Int, 몸: 몸조건, 향: List<향상기록>,
               누적횟수: Int = 0, 운동일수: Int = 0): Pair<플랜, 향상기록> {
    val 예상 = 회표(몸, 향).firstOrNull { it.회 >= 한회 }?.목표값 ?: 지금진행값
    val m = 측정(한회, 날, 무게, 횟수)
    // 같은 회에 이미 측정이 있으면 바꾼다
    val q = copy(측정들 = 측정들.filter { it.회 != 한회 } + m)
    return q to 향상한줄(this, m, 예상, 몸, 누적횟수, 운동일수)
}

/**
 * '지금 실력 넣기' 를 앱데이터에 반영한다 (PlanScreen 고치기 시트가 부른다 · 10-02 감사).
 * 측정 한 줄 + 향상기록 한 줄 — 누적횟수 · 운동일수까지 채운다 (21 문서 5절)
 */
fun 앱데이터.측정넣기(id: String, 날: String, 무게: Double, 횟수: Int): 앱데이터 {
    val p = 플랜들.firstOrNull { it.id == id } ?: return this
    val (누, 일) = 측정사이운동(p, 날)
    val (q, g) = p.측정넣기(날, 무게, 횟수, 몸, 향상기록들, 누, 일)
    return copy(플랜들 = 플랜들.map { if (it.id == id) q else it }, 향상기록들 = 향상기록들 + g)
}

/**
 * 직전 측정 이후 그 종목을 한 **총 반복 수 · 날 수** — 향상기록의 `누적횟수` · `운동일수` (21 문서 5절).
 *  · 직전 측정 = 같은 종목의 향상기록 중 [날] 보다 앞선 마지막 날짜. 없으면 플랜을 만든 날부터 (그것도 없으면 처음부터)
 *  · 그 날 **다음** 부터 [날] 까지 (만든 날부터일 때는 그 날 포함). 같은 날 '한 번 더' 기록도 센다
 *  · 그 종목 = 이 플랜의 줄(플랜id) + 플랜id 없는 같은 이름 줄(바탕 종목 이름 · 플랜 이름)
 *  · 워밍업 세트는 세지 않는다 (볼륨 · 플랜 반영과 같은 규칙)
 */
fun 앱데이터.측정사이운동(p: 플랜, 날: String, 향: List<향상기록> = 향상기록들): Pair<Int, Int> {
    val 직전 = 향.filter { it.종목 == p.종목 && it.날짜 < 날 }.maxOfOrNull { it.날짜 }
    val 이후 = { d: String -> when {
        직전 != null -> d > 직전
        p.만든날.isNotBlank() -> d >= p.만든날
        else -> true
    } }
    var 반복 = 0
    val 날들 = HashSet<String>()
    기록.forEach { (k, rec) ->
        val d = 날짜만(k)
        if (d > 날 || !이후(d)) return@forEach
        val 세트들 = rec.종목들.filter { e -> e.플랜id == p.id || (e.플랜id == null && (e.이름 == p.종목 || e.이름 == p.이름)) }
            .flatMap { it.세트들 }.filter { it.종류 != 세트종류.워밍업 && it.r > 0 }
        if (세트들.isEmpty()) return@forEach
        반복 += 세트들.sumOf { it.r }
        날들 += d
    }
    return 반복 to 날들.size
}

/** 목록 안에서 한 칸 옮기기 — 꾹 눌러 끌기 (동작방식 D3-9 · 01 ㉓-7) */
fun <T> 자리옮김(l: List<T>, 원: Int, 새: Int): List<T> {
    if (원 !in l.indices || 새 !in l.indices || 원 == 새) return l
    val m = l.toMutableList(); val x = m.removeAt(원); m.add(새, x); return m
}

/**
 * 플랜 이름 바꾸기 — 루틴에 넣어 둔 그 플랜 줄의 이름도 같이 바꾼다 (10-01 감시관 지적).
 * (짝짓기는 v0.12.0 부터 플랜id 로 한다. 이름은 화면에 보이는 글이라 같이 바꾼다)
 */
fun 플랜이름바꾸기(d: 앱데이터, id: String, 새이름: String): 앱데이터 {
    val p = d.플랜들.firstOrNull { it.id == id } ?: return d
    val 이름 = 새이름.trim()
    if (이름.isEmpty() || 이름 == p.이름) return d
    return d.copy(
        플랜들 = d.플랜들.map { if (it.id == id) it.copy(이름 = 이름) else it },
        // 플랜에서 넣은 줄(플랜id 가 같은 것)만 — 같은 이름의 일반 종목은 건드리지 않는다 (10-01 감시관)
        루틴들 = d.루틴들.map { r -> r.copy(종목 = r.종목.map { e -> if (e.플랜id == id) e.copy(이름 = 이름) else e }) },
    )
}
