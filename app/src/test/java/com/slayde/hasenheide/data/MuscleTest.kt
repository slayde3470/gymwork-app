    // ── 4. 단계 (07 4절) ──
    private fun 단계() {
        // 맨몸 0kg 은 체중의 60%
        같("맨몸 0kg · 체중 80 → 48", 48.0, 근육계산.유효무게(0.0, 80.0))
        같("맨몸 0kg · 체중 모름 → 1", 1.0, 근육계산.유효무게(0.0, 0.0))
        같("무게가 있으면 그대로", 60.0, 근육계산.유효무게(60.0, 80.0))
        // 처음 하는 근육: 계획대로 다 하면 20, 절반이면 10
        val 계획 = List(4) { 세트(100.0, 10) }
        val 다함 = 근육계산.오늘단계(listOf(근육입력("벤치프레스", 계획, 계획)), 부위없음, 80.0, emptyMap())
        같("처음 · 계획대로 다 함 → 20", 20.0, 다함["chest_mid"] ?: 0.0)
        참("처음 · 보조근(삼두)도 제 계획 대비 20", 근육계산.잎("triceps").all { abs((다함[it] ?: 0.0) - 20.0) < 1e-9 })
        val 반 = 근육계산.오늘단계(listOf(근육입력("벤치프레스", 계획.take(2), 계획)), 부위없음, 80.0, emptyMap())
        같("처음 · 절반 → 10", 10.0, 반["chest_mid"] ?: 0.0)
        // 이전 최대 기준: 이전 최대 4000 과 같은 양을 5세트로 나눠 하면 한 세트에 4단계
        val 최대 = mapOf("chest_mid" to 4000.0)
        val 한세트 = 근육계산.오늘단계(listOf(근육입력("벤치프레스", listOf(세트(80.0, 10)), List(5) { 세트(80.0, 10) })), 부위없음, 80.0, 최대)
        같("이전 최대 4000 · 800 → 4단계", 4.0, 한세트["chest_mid"] ?: 0.0)
        val 넘침 = 근육계산.오늘단계(listOf(근육입력("벤치프레스", List(10) { 세트(80.0, 10) })), 부위없음, 80.0, 최대)
        같("20 에서 멈춘다", 20.0, 넘침["chest_mid"] ?: 0.0)
        // 지금 단계 = 남은 피로 + 오늘
        val f = mapOf("chest_mid" to 피로상태(10.0, 0L, 24 * 시간))
        같("남은 5 + 오늘 4 = 9", 9.0, 근육계산.지금단계(f, mapOf("chest_mid" to 4.0), 12 * 시간)["chest_mid"] ?: 0.0)
        같("남은 10 + 오늘 15 → 20", 20.0, 근육계산.지금단계(f, mapOf("chest_mid" to 15.0), 0L)["chest_mid"] ?: 0.0)
        참("다 풀린 근육은 빠진다", "chest_mid" !in 근육계산.지금단계(f, emptyMap(), 25 * 시간))
    }

    // ── 5. 회복은 곧게 내려간다 (07 5절) ──
    private fun 회복직선() {
        val f = 피로상태(20.0, 0L, 24 * 시간)
        같("시작 전 · 시작 = lv0", 20.0, 근육계산.남은피로(f, -5L))
        같("6시간 뒤 15", 15.0, 근육계산.남은피로(f, 6 * 시간))
        같("18시간 뒤 5", 5.0, 근육계산.남은피로(f, 18 * 시간))
        같("끝 = 0", 0.0, 근육계산.남은피로(f, 24 * 시간))
        같("끝이 지나도 0", 0.0, 근육계산.남은피로(f, 30 * 시간))
        같("피로 없음 = 0", 0.0, 근육계산.남은피로(null, 0L))
        참("다 회복한 잎은 치운다", 근육계산.회복끝치움(mapOf("a" to f, "b" to 피로상태(3.0, 0L, 시간)), 2 * 시간).keys == setOf("a"))
    }

    // ── 6. 07 5절 '확인한 값' ──
    private fun 확인한값() {
        // ① 20단계 · 24시간 → 12시간 뒤 10단계
        val 벤 = listOf(근육입력("벤치프레스", List(4) { 세트(100.0, 10) }))
        val (f1, _) = 근육계산.피로저장(emptyMap(), emptyMap(), 벤, 부위없음, 80.0, 24, 0L)
        같("① 저장 직후 가슴 가운데 20", 20.0, f1.getValue("chest_mid").lv0)
        참("① 끝 = 24시간", f1.getValue("chest_mid").끝 == 24 * 시간)
        같("① 12시간 뒤 10단계", 10.0, 근육계산.남은피로(f1["chest_mid"], 12 * 시간))

        // ② 보조근 8단계 → 9.6시간 뒤 회복
        //    삼두 이전 최대 1000 (삼두 날) · 벤치 1세트 800kg 의 보조근 0.5 = 400 → 20 × 400 ÷ 1000 = 8
        val 삼두잎 = 근육계산.잎("triceps")
        val 최대 = 삼두잎.associateWith { 1000.0 } + mapOf("chest_mid" to 800.0)
        val (f2, _) = 근육계산.피로저장(emptyMap(), 최대, listOf(근육입력("벤치프레스", listOf(세트(80.0, 10)))), 부위없음, 80.0, 24, 0L)
        val 삼두 = f2.getValue(삼두잎.first())
        같("② 보조근 8단계", 8.0, 삼두.lv0)
        참("② 끝 = 9.6시간", 삼두.끝 == (9.6 * 시간).toLong())
        참("② 9.6시간 직전엔 아직 남아 있다", 근육계산.남은피로(삼두, (9.6 * 시간).toLong() - 60_000L) > 0.0)
        같("② 9.6시간 뒤 회복(0)", 0.0, 근육계산.남은피로(삼두, (9.6 * 시간).toLong()))

        // ③ 6시간 뒤 또 20단계 → 끝이 24 → 48시간 (남은 18시간 위에 24시간)
        val (f3, m3) = 근육계산.피로저장(f1, emptyMap(), 벤, 부위없음, 80.0, 24, 6 * 시간)
        val c3 = f3.getValue("chest_mid")
        같("③ 남은 15 + 20 → 20 에서 멈춤", 20.0, c3.lv0)
        참("③ 끝이 24 → 48시간", f1.getValue("chest_mid").끝 == 24 * 시간 && c3.끝 == 48 * 시간)
        참("③ 시작은 두 번째 운동 시각", c3.시작 == 6 * 시간)
        같("③ 27시간 뒤(두 번째 운동 21시간 뒤) 10단계", 10.0, 근육계산.남은피로(c3, 27 * 시간))
        참("③ 이전 최대가 생겼다", (m3["chest_mid"] ?: 0.0) == 4000.0)

        // 회복 시간 설정 — 48시간이면 12시간 뒤 15단계
        val (f4, _) = 근육계산.피로저장(emptyMap(), emptyMap(), 벤, 부위없음, 80.0, 48, 0L)
        같("회복 48시간 · 12시간 뒤 15단계", 15.0, 근육계산.남은피로(f4["chest_mid"], 12 * 시간))
    }

