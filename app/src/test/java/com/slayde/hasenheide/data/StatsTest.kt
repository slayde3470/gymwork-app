object 스탯시험 {

    private var 센 = 0
    private val 틀림 = ArrayList<String>()

    private fun 참(이름: String, 조건: Boolean) { 센++; if (!조건) 틀림.add(이름) }
    private fun 같(이름: String, 기대: Double, 실제: Double?, 허용: Double = 0.01) {
        센++
        if (실제 == null || abs(기대 - 실제) > 허용) 틀림.add("$이름 — 기대 $기대 / 실제 $실제")
    }

    fun 전부(): Int {
        센 = 0; 틀림.clear()
        종목점수시험()
        DOTS시험()
        스탯식()
        스탯기록시험()
        업적표시험()
        업적판정들()
        소급과취소()
        진행막대()
        세기와새칸()
        갱신수같음()
        if (틀림.isNotEmpty()) throw AssertionError("스탯 시험 $센 개 중 ${틀림.size} 개 실패:\n" + 틀림.joinToString("\n") { " · $it" })
        return 센
    }

    // ── 만들기 도구 ──
    private fun 세(w: Double, r: Int, 종류: Int = 0) = 세트(w, r, 종류)
    private fun 종(이름: String, vararg s: 세트, 플랜id: String? = null) = 종목기록(이름, s.toList(), 플랜id = 플랜id)
    private fun 기(vararg 종목: 종목기록, 달성: Boolean = true, 시작: Long = 0L, 끝: Long = 0L, 걸린: Int = 0) =
        날기록("r", "루틴", 달성, 종목.toList(), 걸린, 시작, 끝)
    private fun 데(체중: Double = 100.0, 나이: Int = 35, 남: Boolean = true, vararg 기록: Pair<String, 날기록>) =
        앱데이터(몸 = 몸조건(나이, 남, 체중), 기록 = mapOf(*기록))
    private fun ms(날: String, 시: Int, 분: Int = 0): Long =
        LocalDateTime.parse("${날}T%02d:%02d:00".format(시, 분)).atZone(ZoneId.systemDefault()).toInstant().toEpochMilli()
    private fun 날(기준: String, n: Int) = 날더하기(기준, n)
    private fun 스(d: 앱데이터, 오늘: String, s: 스탯) = d.스탯들(오늘).first { it.스탯 == s }
    private fun 얻음(d: 앱데이터, 오늘: String, 번호: String) = d.업적갱신(오늘, ms(오늘, 12)).first.업적.containsKey(번호)

    // ── 1. 종목점수 (스탯명세 2-4 시험 문제) ──
    private fun 종목점수시험() {
        val 스 = 플랜표.찾기("백 스쿼트")!!; val 벤 = 플랜표.찾기("벤치프레스")!!; val 턱 = 플랜표.찾기("턱걸이")!!
        같("백 스쿼트 100 · 체중 109 · 남 → 25.87", 25.87, 종목점수(100.0 / 109, 스.경계남))
        같("벤치 100 · 체중 100 → 45.71", 45.71, 종목점수(1.0, 벤.경계남))
        같("벤치 200 · 체중 100 → 100 (넘지 않는다)", 100.0, 종목점수(2.0, 벤.경계남))
        같("턱걸이 15회 → 51.43", 51.43, 종목점수(15.0, 턱.횟수경계.map { it.toDouble() }))
        같("턱걸이 0회 → 0", 0.0, 종목점수(0.0, 턱.횟수경계.map { it.toDouble() }))
        같("경계 첫 칸 위 = 정확히 20 · 40 · 60 · 80", 80.0, 종목점수(벤.경계남[3], 벤.경계남))
    }

    // ── 2. DOTS (스탯명세 2-5 시험 문제) ──
    private fun DOTS시험() {
        같("DOTS 270 · 109 · 남 → 160.47", 160.47, DOTS(270.0, 109.0, true))
        같("내 수행능력 = DOTS ÷ 5 → 32.09", 32.09, DOTS(270.0, 109.0, true) / 스탯표.DOTS나눔)
        같("DOTS 500 · 80 · 남 → 344.77", 344.77, DOTS(500.0, 80.0, true))
        같("DOTS 300 · 60 · 여 → 332.56", 332.56, DOTS(300.0, 60.0, false))
        같("체중 250 은 210 으로 자른다", DOTS(300.0, 210.0, true), DOTS(300.0, 250.0, true))
    }

