        val 하 = (종목점수(1.5, 플랜표.찾기("백 스쿼트")!!.경계남) + 종목점수(2.0, 플랜표.찾기("데드리프트")!!.경계남)) / 2
        같("하체 = 평균(스쿼트 1.5배, 데드 2배)", 하, 스(d, 오늘, 스탯.하체).값)
        같("균형 = 100 − |밀기 − 하체| (둘만 있음)", 100 - abs(55.71 - 하), 스(d, 오늘, 스탯.균형).값, 0.02)
        // 다양성 — 부위 가슴(벤치) · 하체(스쿼트) · 등(데드) · 어깨(OHP) = 4, 종목 4 → 50×4/6 + 50×4/12
