    private fun 스탯기록시험() {
        val 오늘 = "2026-10-02"
        val d = 데(100.0, 35, true, 오늘 to 기(종("벤치프레스", 세(100.0, 1))))
        val a = d.스탯기록남김(오늘)
        참("스탯기록 — 오늘 한 줄", a.스탯기록.size == 1 && a.스탯기록[오늘]?.containsKey(스탯.근력.name) == true)
        참("같은 날 같은 값이면 그대로 (다시 저장하지 않는다)", a.스탯기록남김(오늘) === a)
        참("7일 전 기록이 있으면 그것을 쓴다", a.copy(스탯기록 = mapOf(날(오늘, -8) to mapOf(스탯.근력.name to 1.0))).스탯전(오늘)[스탯.근력.name] == 1.0)
        // 체중기록 — 2분 안에 다시 치면 한 줄 (1 → 10 → 109)
        val t = ms(오늘, 9)
        val w = 앱데이터().체중기록잇기(1.0, t).체중기록잇기(10.0, t + 1_000).체중기록잇기(109.0, t + 2_000)
        참("체중을 치는 동안은 한 줄", w.체중기록.size == 1 && w.체중기록[0].kg == 109.0)
        val w2 = w.체중기록잇기(108.0, t + 10 * 60_000)
        참("2분 지나 바꾸면 새 줄", w2.체중기록.size == 2)
        참("같은 값은 남기지 않는다", w2.체중기록잇기(108.0, t + 30 * 60_000) === w2)
    }

