        같("내 수행능력 = DOTS(460, 100, 남) ÷ 5", DOTS(460.0, 100.0, true) / 5, 스(d, 오늘, 스탯.수행능력).값)
        // 밀기 = 평균(벤치 1.1 → 40 + 20×0.2/0.35 = 51.43, OHP 0.6 → 60)
        같("밀기 = 평균(벤치 51.43, OHP 60) = 55.71", 55.71, 스(d, 오늘, 스탯.밀기).값)
