        같("어시스트 보조 0 = 체중", 70.0, 실제무게(기록방식.어시스트, 0.0, 70.0))
        같("어시스트 보조가 체중보다 크면 0", 0.0, 실제무게(기록방식.어시스트, 80.0, 70.0))
        같("체중을 모르면 맨몸 그대로", 5.0, 실제무게(기록방식.맨몸, 5.0, 0.0))
        같("체중을 모르면 어시스트 그대로", 30.0, 실제무게(기록방식.어시스트, 30.0, 0.0))
        같("무게 방식은 그대로", 60.0, 실제무게(기록방식.무게, 60.0, 70.0))
        같("횟수만은 1단계에서 그대로", 5.0, 실제무게(기록방식.횟수만, 5.0, 70.0))
