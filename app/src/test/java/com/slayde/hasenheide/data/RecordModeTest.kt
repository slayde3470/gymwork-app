        참("플랭크는 장비가 맨몸이어도 시간이 먼저", 이름으로방식("플랭크", "맨몸") == 기록방식.시간)
        참("복근 크런치는 맨몸이어도 횟수만이 먼저", 이름으로방식("크런치", "맨몸") == 기록방식.횟수만)
