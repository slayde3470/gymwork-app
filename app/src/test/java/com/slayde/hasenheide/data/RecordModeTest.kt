    // ── 3. 줄이 가리키는 종목으로 ──
    private fun 앱데이터연동() {
        val d = 몸있는데이터(listOf(종목("내 운동", "복근", "맨몸", id = "종1"), 종목("벤치프레스", "가슴", "바벨")))
        참("사전에 없는 커스텀 종목도 장비 맨몸이면 맨몸", d.방식("종1", "내 운동") == 기록방식.맨몸)
        참("종목표에 없어도 사전 이름으로", 앱데이터().방식(null, "턱걸이") == 기록방식.맨몸)
        참("벤치프레스 = 무게", d.방식(null, "벤치프레스") == 기록방식.무게)

        val 세트 = listOf(세트(10.0, 8), 세트(10.0, 8, 세트종류.워밍업))
        val 맨 = d.실제세트들(null, "턱걸이", null, 세트)
        참("맨몸 세트가 실제 무게로", 맨.map { it.w } == listOf(80.0, 80.0) && 맨.map { it.r } == listOf(8, 8))
        참("세트 종류는 그대로", 맨[1].종류 == 세트종류.워밍업)
        참("플랜 줄은 그대로", d.실제세트들(null, "턱걸이", "p1", 세트) == 세트)
        참("무게 종목은 그대로", d.실제세트들(null, "벤치프레스", null, 세트) == 세트)
        참("빈 목록", d.실제세트들(null, "턱걸이", null, emptyList()).isEmpty())
        참("체중을 모르면 그대로", 앱데이터().실제세트들(null, "턱걸이", null, 세트) == 세트)
        참("거꾸로 하면 처음 값", d.입력세트들(null, "턱걸이", null, 맨) == 세트)
        참("플랜 줄은 거꾸로도 그대로", d.입력세트들(null, "턱걸이", "p1", 세트) == 세트)
    }

    private fun 세션(찬: Map<String, List<세트>>, 예정: Map<String, List<세트>> = emptyMap(), 플랜: Set<String> = emptySet()): 운동세션 {
        val 들 = 찬.map { (이름, l) ->
            세션종목(이름, l.size, l.size, l[0].w, l[0].r, 60, 기록 = l, 예정값 = 예정[이름] ?: emptyList(), 플랜id = if (이름 in 플랜) "p1" else null)
        }
        return 운동세션("r1", "등날", 1_000L, 종목들 = 들, 끝화면 = true, 끝시각 = 5_000L, 마지막 = 5_000L)
    }

    // ── 4. 기록에 남길 때 ──
    private fun 저장() {
        val 입력 = linkedMapOf(
            "턱걸이" to listOf(세트(0.0, 8), 세트(10.0, 6)),
            "어시스트 풀업" to listOf(세트(30.0, 10)),
            "벤치프레스" to listOf(세트(60.0, 5)),
            "플랭크" to listOf(세트(0.0, 60)),
        )
        val d0 = 몸있는데이터(루틴들 = listOf(루틴("r1", "등날", 종목 = 입력.map { (n, l) -> 루틴종목(n, l.size, l[0].w, l[0].r) })))
        val S = 세션(입력)
        val d1 = d0.copy(세션 = S).운동저장하기("2026-10-12", 6_000L)
        val rec = d1.기록["2026-10-12"]
        참("기록이 남았다", rec != null)
        if (rec == null) return
        fun 줄(n: String) = rec.종목들.first { it.이름 == n }.세트들
        참("턱걸이 = 체중 + 추가", 줄("턱걸이").map { it.w } == listOf(70.0, 80.0))
        참("어시스트 풀업 = 체중 − 보조", 줄("어시스트 풀업").map { it.w } == listOf(40.0))
        참("벤치프레스 그대로", 줄("벤치프레스") == 입력.getValue("벤치프레스"))
        참("플랭크(시간)는 1단계에서 그대로", 줄("플랭크") == 입력.getValue("플랭크"))
        참("횟수는 그대로", 줄("턱걸이").map { it.r } == listOf(8, 6))
        같("기록 볼륨 = 70×8 + 80×6 + 40×10 + 300", 70.0 * 8 + 80 * 6 + 40 * 10 + 60 * 5, 볼륨(rec.종목들.flatMap { it.세트들 }))
        같("운동 중 볼륨 = 저장된 기록의 볼륨", 볼륨(rec.종목들.flatMap { it.세트들 }), d0.운동중볼륨(S))
        // 루틴에는 입력값(추가 · 보조)이 돌아가 적힌다 — 실제 무게가 아니다
        val 루 = d1.루틴("r1")!!
        참("루틴에는 입력값", 루.종목.first { it.이름 == "어시스트 풀업" }.목표(0).w == 30.0)

        // 플랜 줄은 바꾸지 않는다 (플랜이 따로 셈)
        val 플 = 세션(linkedMapOf("턱걸이" to listOf(세트(69.0, 5))), 플랜 = setOf("턱걸이"))
        같("플랜 줄 볼륨은 그대로", 69.0 * 5, d0.운동중볼륨(플))
        참("플랜 줄 근육 입력도 그대로", 플.근육입력들(d0).first().한것 == listOf(세트(69.0, 5)))

        // 체중을 모르면 옛 동작 그대로
        val d2 = 앱데이터(루틴들 = d0.루틴들).copy(세션 = S).운동저장하기("2026-10-12", 6_000L)
        참("체중 0 이면 맨몸 0 그대로", d2.기록["2026-10-12"]!!.종목들.first { it.이름 == "턱걸이" }.세트들.map { it.w } == listOf(0.0, 10.0))

        // 옛 기록은 건드리지 않는다
        val 옛 = 날기록("r0", "옛", true, listOf(종목기록("턱걸이", listOf(세트(0.0, 9)))))
        val d3 = d0.copy(기록 = mapOf("2026-10-01" to 옛), 세션 = S).운동저장하기("2026-10-12", 6_000L)
        참("옛 기록 그대로", d3.기록["2026-10-01"] == 옛)

        // 같은 날 다시 저장해도 두 번 바뀌지 않는다 (보고서 덮어쓰기 길 — 세션은 늘 입력값)
        val d4 = d3.copy(세션 = S).운동저장하기("2026-10-12", 7_000L, "2026-10-12")
        참("덮어써도 같은 값", d4.기록["2026-10-12"]!!.종목들.first { it.이름 == "턱걸이" }.세트들.map { it.w } == listOf(70.0, 80.0))
    }

    // ── 5. 운동 중 목표 볼륨 ──
    private fun 운동중계산() {
        val d = 몸있는데이터()
        val S = 세션(linkedMapOf("턱걸이" to listOf(세트(0.0, 8))), 예정 = mapOf("턱걸이" to listOf(세트(10.0, 8), 세트(10.0, 8))))
            .let { it.copy(종목들 = it.종목들.map { e -> e.copy(세트 = 2, 기록 = listOf(세트(0.0, 8))) }) }
        같("운동 중 볼륨 = 체크한 세트만, 실제 무게로", 70.0 * 8, d.운동중볼륨(S))
        같("운동 중 목표 볼륨 = 칸마다 보이는 값, 실제 무게로", 70.0 * 8 + 80.0 * 8, d.운동중목표볼륨(S))
        같("방식 없는 옛 계산은 입력값 그대로 (옛 함수 유지)", 0.0, S.오늘볼륨())
    }

    // ── 6. 근육 피로 ──
    private fun 근육() {
        val d = 몸있는데이터()
        val S = 세션(linkedMapOf("턱걸이" to listOf(세트(10.0, 8)), "벤치프레스" to listOf(세트(60.0, 5))))
        val 옛 = S.근육입력들()
        val 새 = S.근육입력들(d)
        참("d 를 안 주면 입력값 그대로", 옛.first { it.이름 == "턱걸이" }.한것.single().w == 10.0)
        참("d 를 주면 맨몸은 실제 무게", 새.first { it.이름 == "턱걸이" }.한것.single().w == 80.0)
        참("무게 종목은 같다", 새.first { it.이름 == "벤치프레스" }.한것 == 옛.first { it.이름 == "벤치프레스" }.한것)
    }

    // ── 7. 지난 기록 → 세션 (거꾸로) ──
    private fun 거꾸로() {
        val d = 몸있는데이터()
        val 입력 = listOf(세트(10.0, 8), 세트(0.0, 6))
        val 실 = d.실제세트들(null, "턱걸이", null, 입력)
        참("저장 → 불러오기 왕복", d.입력세트들(null, "턱걸이", null, 실) == 입력)
