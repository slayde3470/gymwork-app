/**
 * ⇄ 단추 시험 (10-19) — 턱걸이 · 딥스 · 친업의 일반 → 어시스트 → 중량 → 일반.
 * 일반 줄(종목 방식) · 플랜 줄(보조모드) · 운동 중 막기 · 옛 폰 이주를 본다. 화면은 안 본다.
 * 컴퓨터에서 `kotlinc` 로 바로 돌릴 수도 있게 [방식전환시험] 에 `main` 을 두었다 (기록 방식 시험과 같은 방식).
