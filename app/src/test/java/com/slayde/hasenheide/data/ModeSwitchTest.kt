object 방식전환시험 {
    private var 센 = 0
    private val 틀림 = ArrayList<String>()

    private fun 참(이름: String, 조건: Boolean) { 센++; if (!조건) 틀림.add(이름) }
    private fun 같(이름: String, 기대: Double, 실제: Double) { 센++; if (kotlin.math.abs(기대 - 실제) > 0.001) 틀림.add("$이름 — 기대 $기대 · 실제 $실제") }

    @JvmStatic fun main(args: Array<String>) { 전부(); println("방식 전환 시험 통과 ${센}개") }

    fun 전부() {
        센 = 0; 틀림.clear()
        기본방식(); 일반기록(); 모드판정(); 줄전환(); 운동중막기(); 플랜전환시험(); 이주()
        if (틀림.isNotEmpty()) throw AssertionError("방식 전환 시험 틀림 ${틀림.size}개 / $센 개:\n" + 틀림.joinToString("\n"))
    }

    private val 체중 = 70.0

