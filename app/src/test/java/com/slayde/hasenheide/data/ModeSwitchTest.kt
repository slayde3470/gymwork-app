        참("팔굽혀펴기는 단추 없음", d.줄전환모드("팔굽혀펴기", "팔굽혀펴기", null) == null)
        참("종목 방식 어시스트 → 어시스트", d.copy(종목표 = d.종목표.map { if (it.id == "딥스") it.copy(방식 = "어시스트") else it }).줄전환모드("딥스", "딥스", null) == 전환모드.어시스트)
        참("종목 방식 맨몸 → 중량", d.copy(종목표 = d.종목표.map { if (it.id == "딥스") it.copy(방식 = "맨몸") else it }).줄전환모드("딥스", "딥스", null) == 전환모드.중량)
        참("직접 '무게' 로 만든 같은 이름은 단추 없음", d.copy(종목표 = d.종목표.map { if (it.id == "딥스") it.copy(방식 = "무게") else it }).줄전환모드("딥스", "딥스", null) == null)
        참("없는 플랜 줄은 단추 없음", d.줄전환모드("턱걸이", "턱걸이", "없음") == null)
    }

    // ── 4. 일반 줄 ⇄ ──
    private fun 줄전환() {
        var d = 판().copy(세션 = null)
        d = d.종목전환("턱걸이", "턱걸이")
        참("일반 → 어시스트", d.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.어시스트)
        참("종목 방식이 '어시스트' 로 저장", d.종목찾기("턱걸이")?.방식 == "어시스트")
        같("기본 세팅 보조 = 처음 값", 전환표.줄어시스트기본, d.종목설정["턱걸이"]!![0].w)
        같("루틴 줄 보조 = 처음 값", 전환표.줄어시스트기본, d.루틴들[0].종목[0].세트값[1].w)
        참("횟수는 그대로", d.루틴들[0].종목[0].세트값.map { it.r } == listOf(8, 6))
        같("벤치프레스 줄은 그대로", 60.0, d.루틴들[0].종목[1].무게)
        같("어시스트 기록 = 체중 − 보조", 체중 - 전환표.줄어시스트기본, d.실제세트들("턱걸이", "턱걸이", null, listOf(세트(전환표.줄어시스트기본, 8)))[0].w)
        d = d.종목전환("턱걸이", "턱걸이")
        참("어시스트 → 중량", d.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.중량)
        같("중량으로 가면 칸은 0 (추가 없음)", 0.0, d.루틴들[0].종목[0].세트값[0].w)
        같("기본 세팅도 0", 0.0, d.종목설정["턱걸이"]!![0].w)
        d = d.종목전환("턱걸이", "턱걸이")
        참("중량 → 일반", d.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.일반)
        // 어시스트를 언제든 뺄 수 있다 — 어시스트에서 두 번이면 일반
        var e = 판().종목전환("딥스", "딥스")
        참("딥스도 같다", e.줄전환모드("딥스", "딥스", null) == 전환모드.어시스트)
        e = e.종목전환("딥스", "딥스").종목전환("딥스", "딥스")
        참("어시스트에서 두 번이면 일반", e.줄전환모드("딥스", "딥스", null) == 전환모드.일반)
        // 친업 (플랜 없음) 도 일반 줄 ⇄
        참("친업 일반 줄 ⇄", 판().종목전환("친업", "친업").줄전환모드("친업", "친업", null) == 전환모드.어시스트)
        // 대상이 아니면 그대로
        val b = 판()
        참("벤치프레스는 바뀌지 않는다", b.종목전환("벤치프레스", "벤치프레스") == b)
        참("플랜 줄 이름이 같아도 일반 줄 ⇄ 는 플랜을 건드리지 않는다", b.플랜들 == b.종목전환("턱걸이", "턱걸이").플랜들)
        // 같은 이름 둘 — 방식은 id 로 가른다
        val 둘 = 판().let { it.copy(종목표 = it.종목표 + 종목("턱걸이", "등", "맨몸", id = "턱2")) }
        val 둘후 = 둘.종목전환("턱2", "턱걸이")
        참("같은 이름 둘: 고른 것만", 둘후.줄전환모드("턱2", "턱걸이", null) == 전환모드.어시스트 && 둘후.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.일반)
    }

    // ── 5. 운동 중 ──
    private fun 세션(d: 앱데이터, 기록: List<세트?>): 앱데이터 {
        val 줄 = 세션종목("턱걸이", 2, 2, 0.0, 8, 60, 기록 = 기록, 예정값 = listOf(세트(0.0, 8), 세트(0.0, 6)), 종id = "턱걸이")
        return d.copy(세션 = 운동세션("r1", "등날", 1_000L, 종목들 = listOf(줄), 무게 = 0.0, 횟수 = 8))
    }

    private fun 운동중막기() {
        val 빈 = 세션(판(), listOf(null, null))
        참("체크한 세트가 없으면 막히지 않는다", !빈.전환막힘("턱걸이", "턱걸이", null))
        val 후 = 빈.종목전환("턱걸이", "턱걸이")
        참("운동 중 일반 → 어시스트", 후.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.어시스트)
        같("운동 중 줄 예정값도 처음 값으로", 전환표.줄어시스트기본, 후.세션!!.종목들[0].예정값[1]!!.w)
        같("지금 칸 값도", 전환표.줄어시스트기본, 후.세션!!.무게)
        val 찬 = 세션(판(), listOf(세트(0.0, 8), null))
        참("체크한 세트가 있으면 막힌다", 찬.전환막힘("턱걸이", "턱걸이", null))
        참("막히면 그대로", 찬.종목전환("턱걸이", "턱걸이") == 찬)
        참("다른 종목은 막지 않는다", !찬.전환막힘("딥스", "딥스", null))
    }

    // ── 6. 플랜 줄 ⇄ ──
    private fun 플랜판(): 앱데이터 {
        val p = 플랜(id = "p1", 이름 = "턱걸이", 종목 = "턱걸이", 시작1RM = 0.0, 단위 = 목표단위.개수, 시작개수 = 5.0, 목표개수 = 20.0)
        val d = 판().copy(플랜들 = listOf(p), 설정 = 설정값(무게폭 = 1.0))
        return d.copy(루틴들 = d.루틴들 + 루틴("r2", "플랜날", 종목 = listOf(루틴종목("턱걸이", 플랜id = "p1"))))
            .let { x -> x.copy(루틴들 = x.루틴들.map { x.플랜줄채움(it) }) }
    }

    private fun 플랜줄(d: 앱데이터) = d.루틴들.first { it.id == "r2" }.종목[0]

    private fun 플랜전환시험() {
        var d = 플랜판()
        참("플랜 줄은 일반 모드로 시작", d.줄전환모드("턱걸이", "턱걸이", "p1") == 전환모드.일반)
        참("일반 줄은 플랜과 따로", d.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.일반)
        val 일반세트 = 플랜줄(d).세트값
        같("일반 플랜 줄의 무게 = 체중", 체중, 일반세트[0].w)
        d = d.플랜전환("p1")
        참("플랜 일반 → 어시스트", d.플랜들[0].보조모드 == 1 && d.줄전환모드("턱걸이", "턱걸이", "p1") == 전환모드.어시스트)
        같("보조 무게 처음 값", 전환표.플랜어시스트기본, d.플랜들[0].보조무게)
        같("플랜 줄 무게 = 체중 − 보조 (유효 부하)", 체중 - 전환표.플랜어시스트기본, 플랜줄(d).세트값[0].w)
        참("처방 횟수는 5~10", 플랜줄(d).세트값[0].r in 플랜표.어시스트하한..플랜표.어시스트상한)
        참("일반 줄은 그대로", d.줄전환모드("턱걸이", "턱걸이", null) == 전환모드.일반 && d.종목찾기("턱걸이")?.방식 == null)
        참("루틴 r1 의 일반 줄 세트는 그대로", d.루틴들[0].종목[0].세트값.map { it.w } == listOf(0.0, 0.0))
        // 보조 무게 조절
        val 전 = 플랜줄(d).세트값[0].w
        d = d.플랜보조무게("p1", +1)
        같("보조 +1칸 = 5kg", 전환표.플랜어시스트기본 + 전환표.보조한칸, d.플랜들[0].보조무게)
        참("보조를 올리면 무게가 내려간다", 플랜줄(d).세트값[0].w < 전)
        d = d.플랜보조무게("p1", -1).플랜보조무게("p1", -1)
        같("보조 −1칸 (+1 −2)", 전환표.플랜어시스트기본 - 전환표.보조한칸, d.플랜들[0].보조무게)
        var 작게 = d
        repeat(30) { 작게 = 작게.플랜보조무게("p1", -1) }
        참("보조는 1칸 아래로 안 내려간다", 작게.플랜들[0].보조무게 >= 1.0)
        var 크게 = d
        repeat(100) { 크게 = 크게.플랜보조무게("p1", +1) }
        참("어시스트 보조는 체중보다 작게", 크게.플랜들[0].보조무게 < 체중)
        // 직접 입력 (숫자를 눌러 침)
