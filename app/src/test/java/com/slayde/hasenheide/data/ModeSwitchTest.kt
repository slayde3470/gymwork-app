            루틴들 = listOf(루틴("r1", "등날", 종목 = listOf(
                루틴종목("턱걸이", 세트 = 2, 무게 = 0.0, 횟수 = 8, 세트값 = listOf(세트(0.0, 8), 세트(0.0, 6)), 종id = "턱걸이"),
                루틴종목("벤치프레스", 세트 = 1, 무게 = 60.0, 횟수 = 5, 종id = "벤치프레스"),
            ))))
    }

    // ── 1. 처음 방식 ──
    private fun 기본방식() {
        for (n in listOf("턱걸이", "풀업", "친업", "딥스", "평행봉 딥스")) 참("정자세: $n", 이름으로방식(n) == 기록방식.정자세)
        참("벤치 딥스는 그대로 맨몸", 이름으로방식("벤치 딥스") == 기록방식.맨몸)
        참("어시스트 딥스는 어시스트", 이름으로방식("어시스트 딥스") == 기록방식.어시스트)
        참("정자세는 무게 칸이 없다", !기록방식.정자세.무게칸있음())
        참("정자세도 볼륨은 있다", 기록방식.정자세.볼륨있음())
        참("전환 종목은 셋", 전환종목인가("턱걸이") && 전환종목인가("딥스") && 전환종목인가("친업") && 전환종목인가("풀업"))
        참("벤치프레스는 전환 종목이 아니다", !전환종목인가("벤치프레스") && !전환종목인가("팔굽혀펴기"))
    }

    // ── 2. 일반(정자세)의 기록 ──
    private fun 일반기록() {
        val d = 판()
        같("일반 입력 0 → 기록 = 체중", 체중, d.실제세트들("턱걸이", "턱걸이", null, listOf(세트(0.0, 8)))[0].w)
        같("일반은 칸에 남은 옛 값을 무시한다", 체중, d.실제세트들("턱걸이", "턱걸이", null, listOf(세트(10.0, 8)))[0].w)
        같("거꾸로는 0", 0.0, d.입력세트들("턱걸이", "턱걸이", null, listOf(세트(체중, 8)))[0].w)
        같("피로: 일반 = 체중 × 1.0", 체중, d.피로세트들("턱걸이", "턱걸이", null, listOf(세트(0.0, 8)))[0].w)
        같("체중을 모르면 0", 0.0, 앱데이터(종목표 = d.종목표).실제세트들("턱걸이", "턱걸이", null, listOf(세트(0.0, 8)))[0].w)
