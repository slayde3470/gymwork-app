        같("어시스트로 돌아오면 30 (10 이 아니다)", 30.0, d.플랜들[0].보조무게)
        참("처방 무게도 체중 − 30", kotlin.math.abs(플랜줄(d).세트값[0].w - (체중 - 30.0)) < 0.01)
        d = d.플랜전환("p1")                                                 // → 중량: 15 되살림
