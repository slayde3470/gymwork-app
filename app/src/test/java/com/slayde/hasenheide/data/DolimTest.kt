        S = d.시작("r가슴")
        S = S.체크(2, 0, 5000L)
        d = d.저장(S)
        같("다시 — 한 세트라도 하면 넘어감", 1, d.다음("하체"))
        // 넘어감
        d = 판("넘어감")
        S = d.시작("r가슴").다체크(0).다체크(1)
        d = d.저장(S)
        같("넘어감 — 하체 칸도 다음으로", 1, d.다음("하체"))
        같("넘어감 — 가슴 칸도", 1, d.다음("가슴"))
        // 운동 전체를 버리면(체크 0) 아무것도 안 넘어간다
        d = 판("넘어감")
        d = d.copy(세션 = d.시작("r가슴")).운동저장하기(날, 9000L)
        같("체크 없이 끝내면 안 저장 — 하체 그대로", 0, d.다음("하체"))
        같("체크 없이 끝내면 안 저장 — 기록 없음", 0, d.기록.size)
        // 마지막 차례 다음은 처음
        d = 판("넘어감").let { x -> x.copy(돌림들 = x.돌림들.map { if (it.id == "하체") it.copy(다음 = 2) else it }) }
        d = d.저장(d.시작("r가슴").다체크(0))
        같("넘어감 — 마지막 다음은 처음", 0, d.다음("하체"))
    }

