    private fun 운동세션.다체크(j: Int): 운동세션 {
        var S = this
        for (k in 0 until S.종목들[j].세트) S = S.체크(j, k, 5000L + k)
        return S
    }

    private fun 앱데이터.시작(rid: String): 운동세션 = 운동시작(실제루틴(루틴(rid)!!), 1000L)!!

