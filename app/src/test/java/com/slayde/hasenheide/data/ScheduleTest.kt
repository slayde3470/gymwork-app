    private fun 앱데이터.날들(rid: String) = 예정.filterValues { it == rid }.keys.sorted()
    private fun 앱데이터.운동(rid: String, 날: String, 시각: Long = 9000L): 앱데이터 {
        var S = 운동시작(실제루틴(루틴(rid)!!), 1000L)!!
        for (j in S.종목들.indices) for (k in 0 until S.종목들[j].세트) S = S.체크(j, k, 5000L + k)
        return copy(세션 = S.끝냄(시각)).운동저장하기(날, 시각)
    }

