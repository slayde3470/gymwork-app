                    4 -> { val k = d.예정.keys.filter { it >= 오늘 }; if (k.isNotEmpty()) { val 원 = k[난수.nextInt(k.size)]; val 대 = 날더하기(오늘, 난수.nextInt(6)); 로그 += "옮기기 $원 → $대"; d = d.예정옮기기(날짜만(원), 대, 오늘, 원); d.예정.filterKeys { 날짜만(it) == 대 }.forEach { (kk, v) -> 강제 += kk to v } } }
                    5 -> { val 날 = 날더하기(오늘, 난수.nextInt(5)); 로그 += "지우기 $날"; d = d.예정지우기(날, 오늘) }
