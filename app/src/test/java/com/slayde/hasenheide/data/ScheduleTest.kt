    // ── 10-22 감시관: 칸이 여럿인 날의 지우기·미실시 지우기와 되살리기 ──
    private fun 칸여럿왕복() {
        val 날 = 날더하기(목, 2)
        val d0 = 판(이두제외 = emptyList()).예정초기화(목)
        val 칸들 = d0.남은슬롯(날)
        같("가슴/등 묶음 + 이두 묶음 = 한 날 두 칸", 2, 칸들.size)
        val 전 = 칸들.associateWith { d0.예정[it]!! }
        val 지움 = d0.예정지우기(날, 목)
        같("[초기화] 는 그 날 칸을 전부 지운다", 0, 지움.슬롯들(날).size)
        // 화면이 하는 되살리기 (칸마다 예정 + 예정고정 원래대로)
        val 살림 = 전.entries.fold(지움) { acc, (c, rid) -> acc.copy(예정 = acc.예정 + (c to rid), 예정고정 = acc.예정고정 - c) }
        같("되살리면 두 칸 모두 돌아온다", 전, 살림.슬롯들(날).associateWith { 살림.예정[it]!! })
        // 미실시 두 칸 → 지우기 → 칸마다 되살리기
        val 어제 = 날더하기(목, -1)
        val 이름표 = mapOf(슬롯열쇠(어제, 0) to "가슴", 슬롯열쇠(어제, 1) to "이두")
