    /** 언제나 맞아야 하는 것 — 어긋나면 이유를 돌려준다 */
    private fun 점검(d: 앱데이터, 오늘: String, 강제: Set<Pair<String, String>> = emptySet()): String? {
        for ((k, rid) in d.예정) {
            if (d.루틴(rid) == null) return "예정 $k 이 없는 루틴 $rid 를 가리킨다"
            if (슬롯묶음(k) >= 최대묶음) return "칸 번호 넘침 $k"
            if (k.count { it == '#' } > 1 || '~' in k) return "칸 열쇠 모양 이상 $k"
            if (k < 오늘) return "지난 날 칸이 남음 $k"
        }
        // 같은 날 같은 루틴이 두 칸에 있으면 안 된다 (넣기가 막는다 · 다시 깔기는 한 묶음이라 안 겹친다)
        for (날 in d.예정.keys.map { 날짜만(it) }.distinct()) {
            val ids = d.슬롯들(날).map { d.예정[it] }
            if (ids.size != ids.toSet().size) return "$날 에 같은 루틴이 두 칸 $ids"
        }
        // 안 한 자동 칸은 제외 규칙에 걸리는 날에 깔려 있으면 안 된다 — 단 사용자가 직접 놓은 것(고정)은 제외
        for ((k, rid) in d.예정) {
            val r = d.루틴(rid)!!
            if (r.자동생성 && r.제외됨(k) && d.예정고정[k] != rid && (k to rid) !in 강제) return "자동 칸 $k($rid)이 제외 규칙에 걸리는 날"
        }
        // 한 묶음에서 같은 날 두 번 안 깔린다는 것은 열쇠가 맡는다. 기록 열쇠와 칸 열쇠는 안 섞인다
        if (d.기록.keys.any { '#' in it }) return "기록 열쇠에 # 가 섞임"
        // 미실시 열쇠는 지난 날
        for (k in d.미실시.keys) if (날짜만(k) >= 오늘) return "미실시 $k 가 오늘 이후"
        // 예정맞추기는 되풀이해도 더 변하지 않는다 (한 번 맞추면 끝)
        val 한번 = d.예정맞추기(오늘)
        if (한번.예정맞추기(오늘).예정 != 한번.예정) return "예정맞추기를 두 번 하면 한 번과 다르다"
        return null
    }
