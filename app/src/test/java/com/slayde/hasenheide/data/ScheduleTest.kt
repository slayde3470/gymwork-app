        val 이두만 = d0.copy(예정 = d0.예정.filterKeys { 날짜만(it) != 날 } + (슬롯열쇠(날, 1) to "r이두"))
        같("이두 칸만 있는 날도 안 한 칸이 잡힌다", listOf(슬롯열쇠(날, 1)), 이두만.남은슬롯(날))
        같("이두 칸만 있는 날도 [초기화] 가 된다", 0, 이두만.예정지우기(날, 목).슬롯들(날).size)
