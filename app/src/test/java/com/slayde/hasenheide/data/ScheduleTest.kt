                        로그 += "규칙 $rid ${새.map { it.말() }}"; d = d.copy(루틴들 = d.루틴들.map { if (it.id == rid) it.copy(제외 = 새) else it }).예정다시깔기(오늘)
                    }
                    9 -> { val rid = listOf("r가슴", "r등", "r이두")[난수.nextInt(3)]; val b = 난수.nextInt(2); 로그 += "묶음 $rid $b"; d = d.copy(루틴들 = d.루틴들.map { if (it.id == rid) it.copy(묶음 = b) else it }).예정다시깔기(오늘) }
                    else -> { val k = d.예정.keys.filter { it >= 오늘 }; if (k.isNotEmpty()) { val c = k[난수.nextInt(k.size)]; 로그 += "빼기 $c"; d = d.그날빼기(c, 오늘) } }
