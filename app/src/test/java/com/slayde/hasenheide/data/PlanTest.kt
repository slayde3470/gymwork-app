        참("목록 한 칸 옮기기", 자리옮김(listOf("a", "b", "c"), 0, 2) == listOf("b", "c", "a"))
        참("범위 밖은 그대로", 자리옮김(listOf("a", "b"), 0, 5) == listOf("a", "b"))

