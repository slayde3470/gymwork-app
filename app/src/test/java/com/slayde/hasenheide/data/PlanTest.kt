        같정("측정이 하나 남는다", 1, dd.플랜들[0].측정들.size)
        같정("향상기록이 하나 쌓인다", 1, dd.향상기록들.size)
        같정("측정은 그 회차 번호로", 첫측정, dd.플랜들[0].측정들[0].회)

        // ④ 측정 뒤에도 회차 번호가 이어진다 (전에는 1회부터 다시 셌다)
        val 뒤 = dd.플랜들[0].다음회(몸)
        참("측정 뒤 다음 회 = 한회 + 1 (실제 ${뒤?.회})", 뒤?.회 == 첫측정 + 1)

