        참("어시스트 횟수를 안 넣으면 막힌다", 맨몸시작값(턱, 몸, 1, 0.0, 40.0, 0.0) == null)
        같("정자세 5개 → 5", 5.0, 맨몸시작값(팔, 몸, 0, 5.0, 0.0, 0.0) ?: 0.0)
        참("정자세 0 → 막힌다", 맨몸시작값(팔, 몸, 0, 0.0, 0.0, 0.0) == null)
        참("과부하 +10kg×5 → 정자세 5회보다 많다", (맨몸시작값(턱, 몸, 2, 0.0, 10.0, 5.0) ?: 0.0) > 5.0)
        참("바벨 종목은 맨몸 판단을 안 한다", 맨몸시작값(벤, 몸, 0, 5.0, 0.0, 0.0) == null)

