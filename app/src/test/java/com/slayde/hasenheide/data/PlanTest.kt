        같정("10회 한 세트 = 40초", 40, 예상초(r10))
        같정("20회 한 세트 = 80초", 80, 예상초(r20))

        // ⑧ 앞으로의 아무 날이나 지우기 · 미루기
        val 가 = 루틴("a", "가슴", 자동생성 = true, 종목 = listOf(루틴종목("벤치")))
        val 나 = 루틴("b", "등", 자동생성 = true, 종목 = listOf(루틴종목("로우")))
        val 판 = 앱데이터(루틴들 = listOf(가, 나)).예정초기화("2026-10-01")
        val 지움 = 판.예정지우기("2026-10-03", "2026-10-01")
        참("그 날만 지운다", 지움.예정["2026-10-03"] == null && 지움.예정["2026-10-04"] == 판.예정["2026-10-04"])
        val 밈 = 판.날휴식(true, "2026-10-03", "2026-10-01")
