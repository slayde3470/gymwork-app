        val (q, g) = p.copy(한회 = 3).측정넣기("2026-10-01", 70.0, 5, 몸, emptyList())
        같("넣은 값으로 지금 실력이 바뀐다", 일RM(70.0, 5), q.지금진행값)
        참("향상기록에 예상값이 들어간다", g.예상값 > 0)

