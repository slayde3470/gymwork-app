"""v18 A (10-04 홍겸 님) — 운동 화면 세트 줄 · 게이지 · 아래 단추줄
① 끝난 세트 줄(.완료줄) 바탕 = 줄 높이 가운데 50% 만 (위아래 25% 안 칠함) · 색 25% 옅게
   --완료바탕 #E9EEF4 → #EDF1F6 (목록 바탕 --바탕 #F8FAFB 쪽으로 25%) · 다크 #1B2D3F → #162637 (--바탕 #07121E 쪽으로 25%)
② 쉼 게이지 아래쪽 흰 실선 — 원인: 게이지에 1px 테두리가 있고 채움(.위)은 그 안쪽(inset:0 = 테두리 안)에만 깔렸다.
   줄 위치가 소수점(예 473.78px)이라 테두리와 채움이 서로 다르게 픽셀에 맞춰져, 사이 한 줄이 반쯤 비어 흰 바탕이 비쳤다.
   → 테두리를 없애고 안쪽 그림자(inset box-shadow 1px)로 같은 선을 그린다. 채움이 상자 끝까지 덮어 틈이 생길 자리가 없다
③ 마지막 종목의 마지막 세트도 체크하면 휴식 게이지 · 아랫줄 '마무리하고 운동 보고서 화면으로 넘어가기'
   → 누르면 휴식 끝 + 운동 보고서(끝 화면) = '운동 끝내기' 와 같은 행동(data-act="끝내기")
④ '운동 끝내기' 단추 글씨 = --나쁨"""
import sys, pathlib
IN, OUT = sys.argv[1], sys.argv[2]
s = pathlib.Path(IN).read_text(encoding='utf-8')
def 바꿈(old, new, n=1):
    global s
    c = s.count(old)
    if c != n: raise SystemExit(f"❌ {old[:70]!r}: {c}번")
    s = s.replace(old, new)

# ③ 마지막 세트를 끝내도 휴식을 건다 (전에는 다음 세트가 없으면 휴식 없이 끝)
바꿈('''    else { ss.휴식=null; 토스트("모든 세트를 끝냈습니다"); } }''',
     '''    else { ss.휴식={i,k,끝:S.시계+s.휴*1000,길이:s.휴}; 토스트("모든 세트를 끝냈습니다"); } }   // 10-04 v18 ③ 마지막 세트도 똑같이 휴식 게이지''')

# ③ 모든 종목이 끝난 뒤의 휴식 = '마무리하고 운동 보고서 화면으로 넘어가기' → 누르면 '운동 끝내기' 와 같은 행동
바꿈('''  const 쉼글=넘김?"건너뛰고 다음 운동으로 넘어가기":"건너뛰기";
  const 가운데 = 쉼 ? `<button class="쉼게이지 ${넘김?"넘김":""}" data-act="휴식건너뛰기" ''',
     '''  /* 10-04 v18 ③ "마지막 운동의 마지막 세트 … '마무리하고 운동 보고서 화면으로 넘어가기'" — 남은 세트가 하나도 없는 휴식이면
     누르면 휴식을 끝내고 운동 보고서로 ('운동 끝내기' 단추와 같은 행동 = 끝내기) */
  const 마무리=쉼 && ss.종목.every(x=>x.세트.every(y=>y.완료));
  const 쉼글=마무리?"마무리하고 운동 보고서 화면으로 넘어가기":넘김?"건너뛰고 다음 운동으로 넘어가기":"건너뛰기";
  const 가운데 = 쉼 ? `<button class="쉼게이지 ${넘김||마무리?"넘김":""}" data-act="${마무리?"끝내기":"휴식건너뛰기"}" ''')

# ④ '운동 끝내기' 글씨 빨강 — 운동 화면 아랫줄의 그 단추에만 이름표(운끝내기)
바꿈('''<button class="버튼" data-act="끝내기">운동 끝내기</button>''',
     '''<button class="버튼 운끝내기" data-act="끝내기">운동 끝내기</button>''')

css = '''
/* ═══ 10-04 v18 A — 운동 세트 줄 · 게이지 · 끝내기 ═══ */
/* ① 끝난 줄 — 줄 전체가 아니라 높이 가운데 50% 만 칠한다 (위아래 25% 비움). 색은 v17 값에서 목록 바탕(--바탕) 쪽으로 25% 옅게.
   띠는 ::before (절대 위치라 격자 칸을 차지하지 않는다 · isolation 으로 줄 안 맨 뒤에 깔림). 지금 줄(.지금)은 그대로 */
:root{--완료바탕:#EDF1F6}
@media (prefers-color-scheme: dark){ :root:not([data-theme="light"]){--완료바탕:#162637}}
:root[data-theme="dark"]{--완료바탕:#162637}
.운세트들 .세트줄.완료줄{background:none;position:relative;isolation:isolate}
.운세트들 .세트줄.완료줄::before{content:"";position:absolute;inset:25% 0;border-radius:8px;background:var(--완료바탕);z-index:-1;pointer-events:none}
/* ② 게이지 아래 흰 실선 — 테두리(1px) 대신 안쪽 그림자로 같은 선. 채움(.위)이 상자 끝까지 덮어 테두리와 채움 사이 틈이 없다 */
.운세트들 .쉼게이지{border:0;box-shadow:inset 0 0 0 1px var(--강조)}
/* ④ 운동 화면 '운동 끝내기' 글씨 = --나쁨 (빨강) */
.아랫줄 .운끝내기{color:var(--나쁨)}
'''
끝 = s.rfind('</style>'); s = s[:끝] + css + s[끝:]
pathlib.Path(OUT).write_text(s, encoding='utf-8'); print("v18 A →", OUT)
