def 걸림(t): return {k for k,p in 묶음.items() if re.search(p, t)}
흔한말 = set('그 그는 그들 그의 그것 사람 사람들 있었다 있다 했다 없다 없었다 것이다 한다 하나 해 날 그날 그해 이듬해 모두 다른 같은 어느 때 뒤 처음 마지막 지금 이제'.split())
def 낱말(t):
    out=set()
    for w in re.findall(r'[가-힣]{2,}', t):
        w=re.sub(r'(은|는|이|가|을|를|에|에서|의|로|으로|도|만|과|와|까지|부터|이다|였다|이었다|하다|했다|된다|됐다)$','',w)
        if len(w)>=2 and w not in 흔한말: out.add(w)
    return out
업쪽 = [r['이름']+' '+r['칭호']+' '+r['문구']+' '+r['조건'] for r in 업적]
업묶 = [걸림(t) for t in 업쪽]; 업낱 = [낱말(t) for t in 업쪽]
조묶 = [걸림(c['text']) for c in 조각]; 조낱 = [낱말(c['text']) for c in 조각]
def 나쁨(i, j):  # 업적 i 에 조각 j 를 붙이면 겹치는가
    return bool(업묶[i] & 조묶[j]) or bool(업낱[i] & 조낱[j])

rng = random.Random(씨앗)
자리 = list(range(107)); rng.shuffle(자리)          # 자리[i] = 업적 i 에 붙는 조각 번호
처음_나쁨 = [i for i in range(107) if 나쁨(i, 자리[i])]
# 고치기: 나쁜 자리는 다른 자리와 맞바꾼다 — 바꾼 뒤 두 자리 모두 괜찮을 때만
for 돌기 in range(50):
    바뀜 = False
    for i in range(107):
        if not 나쁨(i, 자리[i]): continue
        후보 = list(range(107)); rng.shuffle(후보)
        for k in 후보:
            if k!=i and not 나쁨(i, 자리[k]) and not 나쁨(k, 자리[i]):
                자리[i], 자리[k] = 자리[k], 자리[i]; 바뀜 = True; break
    if not 바뀜: break
남은_나쁨 = [i for i in range(107) if 나쁨(i, 자리[i])]
print('씨앗', 씨앗, '| 섞은 직후 겹침', len(처음_나쁨), '→ 고친 뒤', len(남은_나쁨))
for i in 남은_나쁨: print('  남음', 업적[i]['번호'], 업묶[i] & 조묶[자리[i]], 업낱[i] & 조낱[자리[i]])
# 예전에 홍겸 님이 짚은 것 — 조각이 업적을 겨냥한 것처럼 보이는지 몇 개 직접 보기
보기 = ['2-41','2-43','2-10','2-35','1-8','2-1','2-45','2-47','1-21','2-46']
idx = {r['번호']:i for i,r in enumerate(업적)}
for n in 보기:
    i = idx[n]; print(f'  {n} {업적[i]["칭호"]} ← {조각[자리[i]]["id"]} {조각[자리[i]]["text"]}')
json.dump({업적[i]['번호']: 조각[자리[i]]['id'] for i in range(107)}, open(os.path.join(뿌리,'문서/자료/12-13_플레이버배치.json'),'w',encoding='utf-8'), ensure_ascii=False, indent=0)
assert sorted(자리) == list(range(107))
print('조각 하나당 업적 하나:', len(set(자리)) == 107)
